    public static function valid(string $number): bool
    {
        return (bool) preg_match('/^\d{3}(\.\d+)?$/', $number);
    }

    public static function mainClass(?string $number): ?string
    {
        return $number && self::valid($number) ? $number[0].'00' : null;
    }

    public static function division(?string $number): ?string
    {
        return $number && self::valid($number) ? substr($number, 0, 2).'0' : null;
    }

    /** ชื่อหมวดสำหรับแสดง/สถิติ เช่น "800 วรรณคดี" */
    public static function label(?string $number): ?string
    {
        $main = self::mainClass($number);

        return $main ? $main.' '.self::CLASSES[$main] : null;
    }

    /** อักษรตัวแรกของคำไทย (ข้ามสระหน้า เ แ โ ใ ไ) หรืออังกฤษ */
    public static function initial(?string $text, bool $upper = true): string
    {
        $text = trim((string) $text);
        if ($text === '') {
            return '';
        }
        if (preg_match('/^[เแโใไ]?([ก-ฮ])/u', $text, $m)) {
            return $m[1];
        }
        if (preg_match('/[A-Za-z]/', $text, $m)) {
            return $upper ? strtoupper($m[0]) : strtolower($m[0]);
        }

        return mb_substr($text, 0, 1);
    }

    /** ชื่อที่ใช้ทำเลขผู้แต่ง: ตัดคำนำหน้า · ผู้แต่งไทยใช้ชื่อต้น · ผู้แต่งต่างชาติใช้นามสกุล */
    public static function authorEntry(?string $author): string
    {
        $a = trim((string) $author);
        $a = preg_replace('/^(นางสาว|นาง|นาย|ด\.ช\.|ด\.ญ\.|เด็กชาย|เด็กหญิง|ศ\.ดร\.|รศ\.ดร\.|ผศ\.ดร\.|ดร\.|ศ\.|รศ\.|ผศ\.|อ\.|Dr\.?|Mr\.?|Mrs\.?|Ms\.?)\s*/u', '', $a);
        if ($a === '' || preg_match('/[ก-ฮ]/u', mb_substr($a, 0, 2))) {
            return $a;
        }
        if (str_contains($a, ',')) {
            return trim(explode(',', $a)[0]);
        }
        $parts = preg_split('/\s+/', $a);

        return end($parts);
    }

    /** ชื่อเรื่องที่ใช้ทำอักษรชื่อเรื่อง: ตัด The/A/An นำหน้า */
    public static function titleEntry(?string $title): string
    {
        return preg_replace('/^(the|a|an)\s+/i', '', trim((string) $title));
    }
