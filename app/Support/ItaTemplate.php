    /** สร้างปีใหม่: คัดลอกหัวข้อจากปีก่อนหน้า (ถ้ามี) ไม่งั้นใช้รายการตั้งต้น ไม่คัดลอกหลักฐาน */
    public static function createYear(int $year, ?ItaYear $copyFrom = null): ItaYear
    {
        $new = ItaYear::create(['year' => $year, 'is_published' => false]);
        $rows = $copyFrom
            ? $copyFrom->items->map(fn (ItaItem $i) => [$i->code, $i->group, $i->title, $i->description])->all()
            : array_map(fn ($r) => [$r[0], $r[1], $r[2], null], self::ITEMS);
        foreach (array_values($rows) as $n => [$code, $group, $title, $desc]) {
            $new->items()->create(['code' => $code, 'group' => $group, 'title' => $title, 'description' => $desc, 'sort' => $n + 1]);
        }

        return $new;
    }
