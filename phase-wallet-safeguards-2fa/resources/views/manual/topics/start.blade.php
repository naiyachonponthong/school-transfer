<x-manual.section anchor="two-factor" title="ยืนยันตัวตน 2 ขั้น (ครูและบุคลากร)">
    <p>เข้าสู่ระบบด้วยรหัสผ่าน แล้วตามด้วยรหัส 6 หลักจากแอปบนมือถือ คนที่รู้รหัสผ่านอย่างเดียวจึงเข้าบัญชีไม่ได้ แนะนำสำหรับบัญชีที่ดูแลเงิน ผู้ใช้ หรือการตั้งค่า (โรงเรียนอาจกำหนดให้บัญชีกลุ่มนี้ต้องเปิดใช้)</p>
    <x-manual.steps>
        <li>ติดตั้งแอป <b>Google Authenticator</b> หรือ <b>Microsoft Authenticator</b> บนมือถือ</li>
        <li>เมนูรูปโปรไฟล์ → <span class="ui">ข้อมูลส่วนตัว / รหัสผ่าน</span> → การ์ด <span class="ui">ยืนยันตัวตน 2 ขั้น</span> → <span class="ui">เปิดใช้</span></li>
        <li>สแกน QR ด้วยแอป แล้วกรอกรหัส 6 หลักที่แอปแสดง กด <span class="ui">ยืนยันและเปิดใช้</span></li>
        <li>ระบบแสดง <b>รหัสสำรอง 8 รหัส ครั้งเดียว</b> จดหรือพิมพ์เก็บไว้ ใช้แทนรหัสจากแอปเมื่อมือถือไม่อยู่กับตัว (รหัสละครั้ง)</li>
    </x-manual.steps>
    <x-manual.go route="two-factor.setup">เปิดหน้ายืนยันตัวตน 2 ขั้น</x-manual.go>
    <ul>
        <li>ครั้งต่อไปหลังใส่รหัสผ่าน (หรือเข้าด้วย LINE) ระบบจะถามรหัสจากแอป กรอกผิด 5 ครั้งต้องรอ 15 นาที</li>
        <li><b>เปลี่ยนมือถือ</b>: ปิดการยืนยันตัวตน 2 ขั้นที่หน้าเดิม (ต้องใส่รหัสผ่าน) แล้วเปิดใหม่ด้วยเครื่องใหม่</li>
        <li><b>มือถือหาย</b>: เข้าด้วยรหัสสำรอง ถ้าไม่มีรหัสสำรองให้ผู้ดูแลระบบล้างให้ที่เมนูผู้ใช้งาน</li>
    </ul>
</x-manual.section>

