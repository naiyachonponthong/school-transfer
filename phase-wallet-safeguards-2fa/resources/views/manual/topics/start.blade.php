<x-manual.section anchor="first-password" title="ตั้งรหัสผ่านใหม่ครั้งแรก">
    <p>บัญชีที่ได้รหัสผ่านจากคนอื่น (ผู้ดูแลสร้างหรือรีเซ็ตให้ บัญชีผู้ปกครองที่สร้างอัตโนมัติ บัญชีนักเรียน) <b>ต้องตั้งรหัสผ่านใหม่เองก่อนใช้งาน</b> ระบบจะพาไปหน้า <span class="ui">ตั้งรหัสผ่านใหม่</span> ทันทีที่เข้าระบบ</p>
    <x-manual.steps>
        <li>พิมพ์รหัสผ่านใหม่ <b>อย่างน้อย 8 ตัว มีทั้งตัวอักษรและตัวเลข</b></li>
        <li>ห้ามใช้ชื่อผู้ใช้ เบอร์โทร หรือรหัสเดิม</li>
        <li>พิมพ์ซ้ำอีกครั้งในช่องยืนยัน แล้วกด <span class="ui">บันทึกรหัสผ่านใหม่</span></li>
    </x-manual.steps>
    <p>เปลี่ยนรหัสผ่านเองภายหลังได้ที่ เมนูรูปโปรไฟล์มุมขวาบน → <span class="ui">ข้อมูลส่วนตัว / รหัสผ่าน</span></p>
    <x-manual.go route="profile">เปิดหน้าข้อมูลส่วนตัว</x-manual.go>
</x-manual.section>

<x-manual.section anchor="forgot" title="ลืมรหัสผ่าน">
    <x-manual.steps>
        <li>หน้าเข้าสู่ระบบ กด <span class="ui">ลืมรหัสผ่าน?</span></li>
        <li>กรอกชื่อผู้ใช้ เบอร์โทร หรืออีเมล แล้วกด <span class="ui">ส่งรหัสยืนยันทาง LINE</span></li>
        <li>เปิด LINE ของโรงเรียน จะได้รหัสยืนยัน 6 หลัก <b>ใช้ได้ 10 นาที</b></li>
        <li>กรอกรหัสยืนยันและรหัสผ่านใหม่ แล้วกด <span class="ui">ตั้งรหัสผ่านใหม่</span></li>
    </x-manual.steps>
    <x-manual.callout type="warn">ใช้ได้เฉพาะบัญชีที่ <x-manual.link to="line">เชื่อม LINE</x-manual.link> ไว้แล้ว · กรอกรหัสผิดได้ 5 ครั้ง · ถ้ายังไม่ได้เชื่อม LINE: <b>นักเรียน</b> ติดต่อครูประจำชั้น · <b>ผู้ปกครองและครู</b> ติดต่อผู้ดูแลระบบ ให้รีเซ็ตรหัสผ่านให้ (รหัสใหม่ของผู้ปกครองคือ 6 หลักท้ายเบอร์โทร แล้วระบบให้ตั้งรหัสเองอีกครั้ง)</x-manual.callout>
</x-manual.section>

