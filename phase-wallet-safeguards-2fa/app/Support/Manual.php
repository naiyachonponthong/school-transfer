    {
        return match (self::role($user)) {
            'a' => ['setup', 'start', 'settings', 'users'],
            'p' => ['parent', 'start', 'line'],
            's' => ['student', 'start'],
            default => ['start', 'attendance', 'gradebook', 'line'],
        };
    }
}
