    public static function role(User $user): string
    {
        return match (true) {
            $user->isAdmin() => 'a',
            $user->isParent() => 'p',
            $user->isStudent() => 's',
            default => 't',
        };
    }

    /** หัวข้อที่ผู้ใช้คนนี้เห็น (ผู้ดูแลเห็นทุกหัวข้อ) */
    public static function visible(User $user): array
    {
        $role = self::role($user);

        return array_filter(self::TOPICS, fn ($t) => $role === 'a' || str_contains($t[3], $role));
    }

    public static function canSee(User $user, string $key): bool
    {
        return array_key_exists($key, self::visible($user));
    }

    /** หัวข้อที่ตรงกับหน้าที่กำลังเปิด (ปุ่ม ? บนแถบหัว) */
    public static function forRoute(?string $route, User $user): ?string
    {
        if (! $route) {
            return null;
        }
        foreach (self::visible($user) as $key => $t) {
            foreach ($t[5] as $pattern) {
                if (Str::is($pattern, $route)) {
                    return $key;
                }
            }
        }

        return null;
    }

