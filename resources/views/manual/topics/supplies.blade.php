<p>ครูเขียนใบเบิกวัสดุสิ้นเปลืองจากมือถือ (เหมือนสั่งของออนไลน์) งานพัสดุจ่ายของแล้วระบบ<b>ตัดสต็อก</b>และลง<b>บัญชีวัสดุ</b>ให้อัตโนมัติ เห็นของใกล้หมดก่อนต้องจัดซื้อ</p>

<x-manual.section anchor="request" title="เขียนใบเบิก (ครูทุกคน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">เบิกวัสดุ</span> → <span class="ui">เขียนใบเบิก</span></li>
        <li>ค้นหาหรือกรองตามหมวด ดูรูปและ<b>คงเหลือ</b> (ป้าย <span class="badge bg-warning text-dark">เหลือน้อย</span> / <span class="badge bg-danger">หมด</span>) กด <span class="ui">เพิ่มในใบเบิก</span> แล้วปรับจำนวนด้วยปุ่ม − / +</li>
        <li>ใส่ <b>กลุ่มสาระ / งาน</b> และ <b>ใช้สำหรับ</b> (เช่น จัดทำข้อสอบกลางภาค) ดูมูลค่าโดยประมาณ</li>
        <li>กด <span class="ui">ส่งใบเบิก</span> ได้เลขที่ใบเบิก สถานะ <span class="badge bg-warning text-dark">รอจ่าย</span></li>
    </x-manual.steps>
    <x-manual.go route="requisitions.create">เขียนใบเบิก</x-manual.go>
    <ul>
        <li>ดูสถานะที่ <span class="ui">ใบเบิกของฉัน</span>: รอจ่าย · จ่ายแล้ว (ได้ LINE แจ้ง "มารับได้ที่งานพัสดุ") · ไม่อนุมัติ · ยกเลิก</li>
        <li>เปลี่ยนใจ: เปิดใบเบิก → <span class="ui">ยกเลิกใบเบิก</span> (ระหว่างที่ยังรอจ่าย)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="issue" title="จ่ายวัสดุ (งานพัสดุ / ผู้ดูแล)">
    <x-manual.steps>
        <li>เมนู <span class="ui">คลังวัสดุ</span> → <span class="ui">ใบเบิกรอจ่าย</span> (หรือหน้าเบิกวัสดุ) เปิดใบเบิก</li>
        <li>ตรวจ <b>จำนวนที่ขอ</b> เทียบ <b>คงคลัง</b> แล้วแก้ <b>จำนวนที่จ่าย</b> ถ้าจ่ายไม่ครบ (จ่ายเกินที่ขอหรือเกินคงคลังไม่ได้)</li>
        <li>ใส่หมายเหตุถึงผู้เบิก (ถ้ามี) → <span class="ui">จ่ายวัสดุและตัดสต็อก</span> หรือ <span class="ui">ไม่อนุมัติ</span></li>
        <li>กด <span class="ui">พิมพ์ใบเบิก</span> ให้ผู้เบิกลงชื่อรับของ (มีช่องลงนาม ผู้เบิก · ผู้จ่าย (งานพัสดุ) · ผู้รับของ)</li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="stock" title="คลังวัสดุ: เพิ่มรายการ รับเข้า ปรับยอด">
    <ul>
        <li><b>เพิ่มวัสดุ:</b> ชื่อวัสดุ (เช่น กระดาษ A4 80 แกรม) · หมวด · หน่วยนับ (รีม กล่อง ด้าม ฯลฯ) · ราคาต่อหน่วย · <b>ยอดยกมา</b> · ที่เก็บ (เช่น ห้องพัสดุ ตู้ 2 ชั้น 3) · <b>แจ้งเตือนเมื่อเหลือ ≤</b> (0 = ไม่เตือน) · รูป · สวิตช์ <span class="ui">ยังใช้งาน (ให้ครูเบิกได้)</span></li>
        <li><b>รหัสวัสดุ:</b> <b>เว้นว่าง = ออกรหัสอัตโนมัติ</b> ตามหมวด เช่น <code>OF-001</code> (วัสดุสำนักงาน) <code>CP-012</code> (วัสดุคอมพิวเตอร์)</li>
        <li><b>รับเข้า (ซื้อ/บริจาค):</b> หน้าวัสดุ → <span class="ui">รับเข้า / ปรับยอด</span> ใส่จำนวน ราคาต่อหน่วยล่าสุด หมายเหตุ (เช่น เลขที่ใบส่งของ)</li>
        <li><b>ปรับยอดตามตรวจนับ:</b> หน้าต่างเดียวกัน เลือก <span class="ui">ปรับยอดตามตรวจนับ</span> ใส่ติดลบได้ (เช่น −2 ชำรุด)</li>
        <li>คงเหลือ<b>แก้ตรงๆ ในหน้าแก้ไขไม่ได้</b> ต้องผ่าน "รับเข้า/ปรับยอด" เพื่อให้บัญชีวัสดุถูกต้อง</li>
    </ul>
    <x-manual.go route="supplies.index" manager>เปิดคลังวัสดุ</x-manual.go>
</x-manual.section>

<x-manual.section anchor="ledger" title="บัญชีวัสดุและรายงาน">
    <ul>
        <li>หน้าวัสดุแต่ละรายการ = <b>บัญชีวัสดุ</b> (วันที่ รายการ รับ จ่าย คงเหลือ ราคา ผู้บันทึก) กด <span class="ui">พิมพ์บัญชีวัสดุ</span></li>
        <li>หน้าคลังวัสดุแสดง <b>มูลค่าคงคลัง</b> และกรอง <span class="ui">เฉพาะใกล้หมด</span> เพื่อทำรายการจัดซื้อ</li>
        <li><span class="ui">สรุปรายเดือน</span> — การจ่ายวัสดุแยกตามหน่วยงาน/กลุ่มสาระ พิมพ์ได้</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="numbering" title="ตั้งรูปแบบรหัสวัสดุ">
    <p>คลังวัสดุ → <span class="ui">รูปแบบรหัส</span> เลือกรูปแบบสำเร็จรูป หรือเขียนเอง:</p>
    <ul>
        <li><code>{CAT}-{SEQ3}</code> แยกตามหมวด เลขลำดับ 3 หลัก (ค่าเริ่มต้น) · <code>{CAT}{SEQ}</code> ไม่มีขีด 4 หลัก · <code>M-{SEQ5}</code> ไม่แยกหมวด เรียงทั้งคลัง</li>
        <li>ตัวแทนที่ใช้ได้: <code>{CAT}</code> รหัสหมวด · <code>{FY}</code> ปีงบประมาณ พ.ศ. (ต.ค.–ก.ย.) · <code>{FY2}</code> ปีงบ 2 หลัก · <code>{YEAR}</code> ปี พ.ศ. · <code>{SEQ}</code> เลขลำดับ (<code>{SEQ3}</code>–<code>{SEQ6}</code> เปลี่ยนจำนวนหลัก)</li>
        <li>ตั้ง<b>รหัสหมวด</b>แต่ละหมวดได้ (ค่าเริ่มต้น OF CP ED HK EL SC SP CN FU OT)</li>
    </ul>
    <x-manual.callout type="note">เปลี่ยนรูปแบบแล้ว รหัสเดิมไม่เปลี่ยน มีผลกับวัสดุที่เพิ่มใหม่เท่านั้น</x-manual.callout>
</x-manual.section>
