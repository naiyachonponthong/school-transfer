<p>ผู้ปกครองสมัครเรียนออนไลน์จากมือถือได้เองโดย<b>ไม่ต้องมีบัญชี</b> (ใช้เลขบัตรประชาชน + วันเกิด + เบอร์โทร) กรอกค้างไว้แล้วกลับมาทำต่อได้ โรงเรียนตรวจใบสมัคร รับค่าสมัคร จัดสอบ ประกาศผล จนถึง<b>มอบตัว</b>ที่สร้างข้อมูลนักเรียนและบัญชีผู้ปกครองให้ทันที</p>

<x-manual.section anchor="form" title="1. ตั้งค่าฟอร์มรับสมัคร (ผู้ดูแลระบบ)">
    <x-manual.steps>
        <li>เมนู <span class="ui">รับสมัครนักเรียน</span> → <span class="ui">ตั้งค่าฟอร์มรับสมัคร</span></li>
        <li><b>การเปิดรับสมัคร:</b> สวิตช์ <span class="ui">เปิดรับสมัคร</span> · <b>เปิดรับตั้งแต่ – ถึงวันที่</b> · <b>ระดับชั้นที่เปิดรับ</b> (คั่นด้วยจุลภาค เช่น ป.1,ม.1,ม.4) · <b>รับใบสมัครไม่เกิน (คน)</b> ต่อชั้น (ครบแล้วขึ้น "เต็มแล้ว")</li>
        <li><b>ค่าสมัครและเอกสาร:</b> ค่าสมัคร (บาท — 0 = ไม่เก็บ) · ข้อความเรื่องการชำระเงิน · ข้อความหัวฟอร์ม · ข้อความรับรองในใบมอบตัว · ข้อความ PDPA</li>
        <li><b>ช่องหลัก</b> บังคับกรอกเสมอ · <b>ช่องเสริม</b> ตั้งเป็น แสดง / บังคับ / ซ่อน ได้</li>
        <li><b>คำถามของโรงเรียน:</b> <span class="ui">เพิ่มคำถาม</span> เลือกชนิด ข้อความสั้น/ยาว ตัวเลข วันที่ ตัวเลือก (ดรอปดาวน์ / เลือกข้อเดียว / หลายข้อ) หรือแนบไฟล์ (รูป/PDF) เช่น ความสามารถพิเศษ แผนการเรียนที่เลือก สำเนาทะเบียนบ้าน ปพ.1 · กำหนดว่าบังคับตอบหรือไม่</li>
        <li>สวิตช์ พิมพ์ <b>ส่วนที่ 2 สำหรับผู้สมัคร</b> (ห้องสอบ/เลขที่นั่งสอบ) ท้ายใบสมัคร — ใช้เป็นบัตรเข้าห้องสอบ</li>
        <li>กด <span class="ui">ดูฟอร์มจริง</span> ทดลอง แล้ว <span class="ui">บันทึกฟอร์ม</span></li>
    </x-manual.steps>
    <x-manual.go route="admissions.form" admin>ตั้งค่าฟอร์มรับสมัคร</x-manual.go>
    <x-manual.callout type="tip">กด <span class="ui">คัดลอกลิงก์สมัคร</span> ที่หน้ารับสมัคร แล้วโพสต์ลงเพจ/กลุ่ม LINE ของโรงเรียน หรือทำเป็น QR ติดประกาศ</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="apply" title="2. ผู้ปกครองสมัคร (ไม่ต้องเข้าสู่ระบบ)">
    <x-manual.steps>
        <li>เปิดลิงก์สมัคร → ใส่ <b>ระดับชั้นที่สมัคร · เลขประจำตัวประชาชนผู้สมัคร · วันเกิด · เบอร์โทรผู้ปกครอง</b> → <span class="ui">เริ่มสมัคร หรือ กลับมากรอกต่อ</span></li>
        <li>กรอกทีละขั้น: <b>ข้อมูลผู้สมัคร → การศึกษาเดิม → ผู้ปกครองและที่อยู่ → ข้อมูลเพิ่มเติม → เอกสารแนบ</b> (บันทึกทุกขั้น ปิดเครื่องแล้วกลับมาต่อด้วยข้อมูลชุดเดิมได้)</li>
        <li><span class="ui">ตรวจสอบและยืนยัน</span> → <span class="ui">ส่งใบสมัคร</span> ได้ <b>เลขที่ใบสมัคร</b> (เช่น A25700001)</li>
        <li>ถ้ามีค่าสมัคร: โอนเข้าบัญชีแล้วแนบสลิป</li>
        <li>ติดตามที่ <span class="ui">ดูสถานะและพิมพ์เอกสาร</span>: ผลการพิจารณา เลขประจำตัวสอบ ห้องสอบ เลขที่นั่ง คะแนนและอันดับ พิมพ์ใบสมัคร ใบเสร็จค่าสมัคร และใบมอบตัว</li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="review" title="3. ตรวจใบสมัคร (ผู้ดูแลระบบ)">
    <ul>
        <li>หน้ารับสมัครแสดงสรุปรายชั้น กรองตามชั้น/สถานะ ค้นหาชื่อ เลขที่ใบสมัคร เลขบัตร · <span class="ui">ส่งออก Excel</span></li>
        <li>เปิดใบสมัคร: ตรวจข้อมูลและ <span class="ui">เปิดไฟล์แนบ</span> · ค่าสมัคร: <span class="ui">ดูสลิป</span> → <span class="ui">ยืนยันสลิป · ออกใบเสร็จ</span> หรือ <span class="ui">ตีกลับสลิป</span> (สมัครที่โรงเรียนและจ่ายเงินสด: <span class="ui">รับเงินสด · ออกใบเสร็จ</span>)</li>
        <li><b>ผลการพิจารณา:</b> ส่งใบสมัครแล้ว · กำลังตรวจสอบ · ผ่านการคัดเลือก · สำรอง · ไม่ผ่าน พร้อมหมายเหตุถึงผู้สมัคร</li>
        <li>ห้องสอบ/เลขที่นั่ง/เลขประจำตัวสอบ ใส่รายคนได้ แต่แนะนำให้ <span class="ui">จัดทั้งชั้นอัตโนมัติ</span> ใน <x-manual.link to="admission-exams" /></li>
        <li><span class="ui">พิมพ์</span> ใบสมัคร ใบเสร็จค่าสมัคร ใบมอบตัว ได้จากหน้านี้</li>
    </ul>
