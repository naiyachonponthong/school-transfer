<x-manual.section anchor="enroll" title="4. มอบตัว">
    <x-manual.steps>
        <li>ผู้ผ่านการคัดเลือกพิมพ์ใบมอบตัว กรอก ลงนาม แล้วนำมาวันมอบตัว</li>
        <li>เจ้าหน้าที่เปิดใบสมัคร → <span class="ui">มอบตัว (สร้างนักเรียนในระบบ)</span> ใส่ <b>รหัสนักเรียน</b> และเลือก <b>ห้องเรียน</b> (เว้นไว้จัดห้องภายหลังได้) → <span class="ui">ยืนยันมอบตัว</span></li>
        <li>ระบบสร้างข้อมูลนักเรียน (ต่อเลขที่ท้ายห้อง) และบัญชีผู้ปกครองจากเบอร์โทรที่สมัคร (มีบัญชีอยู่แล้ว = ผูกกับบัญชีเดิม) สถานะเป็น <b>มอบตัวแล้ว</b></li>
    </x-manual.steps>
    <x-manual.callout type="note">การรับสมัครเป็นของ<b>ปีการศึกษาถัดไป</b>เสมอ — สร้างห้องเรียนของปีใหม่ (ดู <x-manual.link to="year" />) ก่อนวันมอบตัว เพื่อเลือกห้องได้เลย</x-manual.callout>
</x-manual.section>
