<p>ตรวจข้อสอบปรนัย 4 ตัวเลือก (สูงสุด 100 ข้อต่อแผ่น) ด้วยกล้องมือถือ ไม่ต้องใช้เครื่องตรวจข้อสอบ ทั้งหมด 5 ขั้น: <b>เฉลย → กระดาษคำตอบ → สแกน → ผลตรวจ → วิเคราะห์ข้อสอบ</b> (แท็บด้านบนของชุดข้อสอบ)</p>

<x-manual.section anchor="create" title="1. สร้างชุดข้อสอบ">
    <x-manual.steps>
        <li>เมนู <span class="ui">ตรวจข้อสอบ</span> → <span class="ui">สร้างชุดข้อสอบ</span></li>
        <li>ตั้งชื่อการสอบ (เช่น สอบกลางภาค) จำนวนข้อ วันสอบ เลือกรายวิชา และติ๊กห้องที่สอบ (หลายห้องได้ ต้องเป็นวิชาเดียวกัน)</li>
    </x-manual.steps>
    <x-manual.go route="exams.index">เปิดหน้าตรวจข้อสอบ</x-manual.go>
</x-manual.section>

<x-manual.section anchor="key" title="2. ใส่เฉลย">
    <ul>
        <li><b>คลิก</b>วงตัวเลือกของแต่ละข้อ หรือคลิกข้อ 1 แล้ว<b>พิมพ์ต่อเนื่อง</b> <kbd>1</kbd>–<kbd>4</kbd> หรือ <kbd>ก</kbd>–<kbd>ง</kbd> (แป้นไทยก็ได้) · <kbd>X</kbd> ยกเลิกข้อ · <kbd>Backspace</kbd> ลบ</li>
        <li><b>วางเฉลย</b> จากแถว KEY ของ EVANA หรือ Excel เช่น <code>2333112…</code> หรือ <code>ข ค ค ค ก</code> แล้วกด <span class="ui">ใส่เฉลยจากข้อความ</span></li>
        <li>เปิด <span class="ui">ข้อที่ถูกได้หลายตัวเลือก</span> ถ้ามีข้อที่ตอบได้มากกว่า 1 คำตอบ</li>
        <li>ตั้ง <b>คะแนนต่อข้อ</b> และวิธีจัดการ <b>ข้อที่ยกเลิก</b>: ให้คะแนนทุกคน หรือ ตัดออกจากคะแนนเต็ม</li>
        <li>ช่อง <span class="ui">ทดลองตรวจ</span> พิมพ์คำตอบของนักเรียน 1 คน เพื่อเช็กว่าเฉลยถูกก่อนใช้จริง</li>
        <li>กด <span class="ui">บันทึกเฉลย</span></li>
    </ul>
    <x-manual.callout type="tip"><b>แก้เฉลยทีหลังได้เสมอ</b> ระบบตรวจทุกแผ่นที่สแกนไปแล้วใหม่ให้อัตโนมัติ (เช่น พบว่าข้อ 15 เฉลยผิด หรือต้องยกเลิกข้อ)</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="sheets" title="3. พิมพ์กระดาษคำตอบ">
    <ul>
        <li><b>รายบุคคล (แนะนำ)</b> — พิมพ์ชื่อและระบายเลขประจำตัว 5 หลัก + เลขที่ให้แล้ว นักเรียนระบายแค่คำตอบ ลดการระบายรหัสผิด เลือกพิมพ์ทุกห้องหรือทีละห้อง</li>
        <li><b>แผ่นเปล่า</b> — นักเรียนเขียนชื่อ ระบายเลขประจำตัว 5 หลักและเลขที่เอง</li>
        <li>แก้ข้อความหัวกระดาษได้ (รายวิชา วิชาในกรอบ วันสอบ ชื่อโรงเรียนและตรา)</li>
    </ul>
    <x-manual.callout type="warn">ตั้งเครื่องพิมพ์: <b>A4 · ขนาดจริง 100% · ไม่ย่อให้พอดีหน้า · ปิดหัว/ท้ายกระดาษ</b> · ห้ามเขียนทับ เย็บ หรือเจาะบริเวณสี่เหลี่ยมดำ 4 มุม ขีดดำขอบขวา และแถบ 10 ช่องด้านล่าง เพราะเครื่องใช้หาตำแหน่ง · ให้นักเรียนใช้ดินสอ 2B ระบายเต็มวง</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="scan" title="4. สแกนด้วยมือถือ">
    <x-manual.steps>
        <li>เปิดแท็บ <span class="ui">สแกน</span> บนมือถือ → <span class="ui">เปิดกล้องสแกน</span> อนุญาตใช้กล้อง</li>
        <li>วางกระดาษบนพื้นเรียบ แสงสว่างพอ ให้เห็น<b>สี่เหลี่ยมดำครบ 4 มุม</b></li>
        <li>กรอบเป็น<b>สีเขียว</b> → ถือนิ่ง ระบบถ่ายเอง (หรือกดปุ่มกลม) แผ่นปกติบันทึกเองใน 1–2 วินาที วางแผ่นถัดไปได้เลย · แผ่นที่ต้องดูจะหยุดรอ</li>
        <li>ทำต่อจนครบ แล้วกด <span class="ui">ไปหน้าผลตรวจ / ตรวจทาน</span></li>
    </x-manual.steps>
    <ul>
        <li><b>ไม่มีเน็ตก็สแกนได้</b> ผลเก็บในเครื่องแล้วส่งเองเมื่อมีเน็ต (หรือกด <span class="ui">ส่งตอนนี้</span>) ส่งซ้ำไม่เกิดแผ่นซ้ำ</li>
        <li>ใช้มือถือหลายเครื่องสแกนพร้อมกันได้ (แบ่งกันคนละห้อง)</li>
        <li><b>สแกนจากรูป</b> — เลือกได้หลายรูป หรือไฟล์จากเครื่องสแกนเอกสาร (ใช้เมื่อกล้องเปิดไม่ได้)</li>
        <li><b>ความไวในการอ่าน</b>: ปกติ (ดินสอ 2B) · ไวขึ้น (ดินสอจาง/แสงน้อย) · ไวน้อยลง (มีรอยลบเยอะ)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="review" title="5. ผลตรวจและตรวจทาน">
    <ul>
        <li>แท็บ <span class="ui">รอตรวจทาน</span> — แผ่นที่ระบบไม่แน่ใจ (ไม่พบเลขประจำตัว ระบายรหัสไม่ครบ ตอบซ้อน อ่านไม่ชัด สแกนซ้ำ เลขที่ไม่ตรง) กด <span class="ui">ตรวจทานทีละแผ่น</span> จะเห็นภาพจริงเทียบวงที่ระบบอ่าน แก้คำตอบ/เลือกเจ้าของแผ่น แล้วบันทึก</li>
        <li>แผ่นของนักเรียนคนเดียวกันซ้ำ ระบบถามก่อนว่าจะใช้แผ่นใหม่แทน (แผ่นเดิมถูกยกเลิก ไม่ลบ)</li>
        <li>แท็บ <span class="ui">ตารางคะแนน</span> — คะแนนทุกคน คนที่ไม่มีแผ่น = ขาดสอบ · สถิติ เฉลี่ย S.D. สูงสุด/ต่ำสุด มัธยฐาน</li>
        <li><span class="ui">ส่งเข้าสมุดคะแนน</span> — เลือกช่องคะแนน ระบบแปลงสัดส่วนตามคะแนนเต็มของช่องให้ ทุกห้องในครั้งเดียว</li>
        <li><span class="ui">ส่งออกคะแนน</span> (Excel) และ <span class="ui">แบบ EVANA</span> (แถว KEY + คำตอบรายคน)</li>
        <li>ตั้งค่าชุดข้อสอบ: เปิด <span class="ui">ให้นักเรียน/ผู้ปกครองเห็นคะแนนสอบนี้</span> เมื่อพร้อมประกาศ</li>
    </ul>
</x-manual.section>

