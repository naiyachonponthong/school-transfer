<x-manual.section anchor="discount" title="ส่วนลดประจำตัวนักเรียน">
    <p>บันทึกส่วนลดให้นักเรียนรายคน เช่น บุตรบุคลากร พี่น้อง ทุน เป็นจำนวนเงินหรือร้อยละ เมื่อออกใบแจ้งหนี้จากผัง ระบบหักส่วนลดให้อัตโนมัติและแสดงเป็นบรรทัดในใบแจ้งหนี้</p>
</x-manual.section>

<x-manual.section anchor="installment" title="ผ่อนชำระ">
    <p>ใบแจ้งหนี้ที่แบ่งชำระเป็นงวดจะแสดงตารางงวด (วันครบกำหนดและยอดของแต่ละงวด) ในหน้าใบแจ้งหนี้ ทั้งฝั่งการเงินและผู้ปกครองเห็นเหมือนกัน</p>
</x-manual.section>

<x-manual.section anchor="void" title="ยกเลิกใบเสร็จ">
    <p>ใบเสร็จที่ออกผิดให้<b>ยกเลิก</b>พร้อมระบุเหตุผล ไม่ลบทิ้ง เลขที่ใบเสร็จจะไม่ถูกนำมาใช้ซ้ำ และยอดค้างของใบแจ้งหนี้กลับมาตามเดิม</p>
</x-manual.section>

