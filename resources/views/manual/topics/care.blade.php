    <x-manual.steps>
        <li>เปิดหน้า <span class="ui">ดูแลช่วยเหลือ</span> ระบบแสดงนักเรียนที่มีสัญญาณเสี่ยง 4 แบบ: ขาดเรียนติดกัน เวลาเรียนรายวิชาต่ำกว่า 80% คะแนนต่ำหลายวิชา และความประพฤติต่ำกว่าเกณฑ์</li>
        <li>กด <span class="ui">เปิดกรณี</span> ที่นักเรียนคนนั้น เลือกด้าน ระดับ ผู้รับผิดชอบ และเขียนสิ่งที่พบ</li>
