<p>ระบบดูแลช่วยเหลือนักเรียนของครูประจำชั้น: ดูสัญญาณเสี่ยง เปิดกรณีติดตาม เยี่ยมบ้าน ครูเห็นเฉพาะห้องของตัวเอง ผู้มีสิทธิ์ดูแลช่วยเหลือเห็นทุกห้อง</p>

