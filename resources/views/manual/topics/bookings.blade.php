<p>จองห้องประชุม ห้องปฏิบัติการ รถตู้ หรืออุปกรณ์ (โปรเจกเตอร์ เครื่องเสียง) โดยเห็นช่วงเวลาที่ถูกจองแล้วก่อนกดจอง ระบบกันการจองซ้อนเวลาอัตโนมัติ</p>

<x-manual.section anchor="book" title="จอง">
    <x-manual.steps>
        <li>เมนู <span class="ui">จองห้อง/รถ</span> → <span class="ui">จอง</span> (หรือกด <span class="ui">จอง</span> ที่การ์ดของห้อง/รถนั้น)</li>
        <li><b>1. เลือกห้อง / รถ / อุปกรณ์</b> ทางซ้าย กรองตามประเภทได้ ดูรูป ความจุ สิ่งอำนวยความสะดวก และป้าย <span class="badge bg-warning text-dark">ต้องอนุมัติ</span></li>
        <li><b>2. รายละเอียดการจอง</b>: เลือก <b>วันที่</b> → ดู <span class="ui">ตารางจอง</span> ของวันนั้น (แถบสี = ช่วงที่ถูกจองแล้ว พร้อมชื่อผู้จอง) → ใส่เวลา <b>ตั้งแต่ – ถึง</b> แถวล่างจะแสดงช่วงที่เลือก ถ้าขึ้น <span class="text-success">ช่วงที่เลือกว่าง</span> จองได้</li>
        <li>ใส่ <b>วัตถุประสงค์</b> จำนวนคน หมายเหตุ (เช่น ขอไมค์ 2 ตัว จัดโต๊ะแบบ U) เบอร์ติดต่อ · <b>รถ:</b> ใส่ปลายทาง และ <span class="ui">ถึงวันที่ (ค้างคืน)</span> ถ้าไปหลายวัน</li>
        <li>อ่าน <b>ข้อปฏิบัติ</b> ของห้อง/รถ แล้วกด <span class="ui">จอง</span></li>
    </x-manual.steps>
    <x-manual.go route="bookings.create">จองเลย</x-manual.go>
    <ul>
        <li>รายการที่ <b>ต้องอนุมัติ</b> จะเป็น <span class="badge bg-warning text-dark">รออนุมัติ</span> (กันเวลาไว้ให้แล้ว คนอื่นจองทับไม่ได้) และได้แจ้งเตือนเมื่ออนุมัติ/ไม่อนุมัติ</li>
        <li>รายการที่ไม่ต้องอนุมัติ = <span class="badge bg-success">อนุมัติแล้ว</span> ทันที</li>
        <li>ยกเลิกได้จาก <span class="ui">การจองของฉัน</span> → <span class="ui">ยกเลิก</span> (ก่อนเวลาสิ้นสุด)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="approve" title="อนุมัติการจอง (งานพัสดุ / ผู้ดูแล)">
    <p>หน้าจองห้อง/รถ แสดงรายการ <b>รออนุมัติ</b> ด้านบน ใส่หมายเหตุ (ถ้ามี) แล้วกด <span class="ui">อนุมัติ</span> หรือ <span class="ui">ไม่อนุมัติ</span> — ผู้จองได้แจ้งเตือนทันที · ยกเลิกการจองของคนอื่นได้ (ระบบแจ้งผู้จองและบันทึกประวัติ)</p>
</x-manual.section>

