<p>คุมเงินของโรงเรียนตั้งแต่แผนจนถึงการขอใช้: แหล่งเงินของปีงบประมาณ → โครงการ → งบของโครงการ → ใบขอซื้อ/ขอจ้าง → อนุมัติ ทุกใบตัดยอดจากงบของโครงการ จึงรู้เสมอว่าแต่ละโครงการเหลือเงินเท่าไร</p>

<x-manual.section anchor="terms" title="คำที่ใช้">
    <ul>
        <li><b>ปีงบประมาณ</b>: 1 ตุลาคม – 30 กันยายน เรียกตามปี พ.ศ. ของเดือนกันยายน</li>
        <li><b>จัดสรร</b>: เงินจากแหล่งเงินที่แบ่งให้โครงการแล้ว</li>
        <li><b>รออนุมัติ</b>: ใบขอซื้อที่ยื่นแล้วยังพิจารณาไม่ครบ เงินถูกกันไว้ ใบอื่นจะขอซ้อนจนเกินงบไม่ได้</li>
        <li><b>ผูกพัน</b>: ใบขอซื้อที่อนุมัติครบทุกขั้นแล้ว เงินถูกกันไว้สำหรับการซื้อนั้น</li>
        <li><b>คงเหลือ</b> = งบ − ผูกพัน − รออนุมัติ</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="setup" title="ตั้งแหล่งเงินและโครงการ (ฝ่ายการเงิน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">งบประมาณ</span> → <span class="ui">เพิ่มแหล่งเงิน</span> ใส่ชื่อ (เช่น เงินอุดหนุนรายหัว) และวงเงินที่ได้รับของปีงบประมาณ</li>
        <li>เมนู <span class="ui">โครงการ</span> → <span class="ui">ตั้งโครงการ</span> ใส่ชื่อ ผู้รับผิดชอบ หน่วยงาน ช่วงเวลา ระบบออกรหัสโครงการให้</li>
        <li>ในหน้าโครงการ กด <span class="ui">เพิ่ม/แก้งบ</span> เลือกแหล่งเงิน หมวดรายจ่าย และจำนวนเงิน ทำซ้ำได้หลายบรรทัด</li>
    </x-manual.steps>
    <x-manual.go route="budget.index">เปิดหน้างบประมาณ</x-manual.go>
    <ul>
        <li>จัดสรรให้โครงการรวมกันเกินวงเงินของแหล่งเงินไม่ได้ และลดงบต่ำกว่ายอดที่ผูกพันและรออนุมัติแล้วไม่ได้</li>
        <li>หน้างบประมาณตั้ง <b>ขั้นอนุมัติ</b> ได้: ผู้รับผิดชอบโครงการ → เจ้าหน้าที่พัสดุ → เจ้าหน้าที่การเงิน → ผู้อำนวยการ ติ๊กเฉพาะขั้นที่โรงเรียนใช้ มีผลกับใบที่ยื่นหลังจากนั้น</li>
        <li>ผู้พิจารณาแต่ละขั้นกำหนดด้วยสิทธิ์ของตำแหน่งงาน ดูได้ที่<x-manual.link to="roles">ตำแหน่งงานและสิทธิ์</x-manual.link></li>
    </ul>
</x-manual.section>

<x-manual.section anchor="request" title="เขียนใบขอซื้อ/ขอจ้าง (ครูทุกคน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ขอซื้อ/ขอจ้าง</span> → <span class="ui">เขียนใบขอซื้อ/ขอจ้าง</span></li>
        <li>เลือก <b>งบที่ใช้</b> (โครงการและหมวดรายจ่าย) ระบบบอกงบคงเหลือของบรรทัดนั้น</li>
        <li>ใส่เรื่อง เหตุผล วิธีจัดหา แล้วเพิ่มรายการพร้อมจำนวนและราคาต่อหน่วย ยอดรวมคิดให้เอง</li>
        <li>กด <span class="ui">ยื่นขออนุมัติ</span> ผู้พิจารณาขั้นแรกได้รับแจ้งเตือน</li>
    </x-manual.steps>
    <x-manual.go route="purchases.create">เขียนใบขอซื้อ/ขอจ้าง</x-manual.go>
    <ul>
        <li>ยอดรวมเกินงบคงเหลือจะยื่นไม่ได้ ให้ลดรายการหรือขอให้ฝ่ายการเงินปรับงบของโครงการ</li>
        <li>ติดตามสถานะและดูว่ารอใครอยู่ได้ในหน้าใบขอซื้อ ยกเลิกเองได้ตราบที่ยังอนุมัติไม่ครบ</li>
        <li>กด <span class="ui">พิมพ์บันทึกข้อความ</span> เพื่อพิมพ์ใบพร้อมช่องลงนามของทุกขั้น</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="approve" title="พิจารณาใบขอซื้อ/ขอจ้าง">
    <x-manual.steps>
        <li>เมนู <span class="ui">ขอซื้อ/ขอจ้าง</span> ส่วน <span class="ui">รอคุณพิจารณา</span> แสดงใบที่ถึงขั้นของคุณ (ตัวเลขบนเมนูคือจำนวนใบ)</li>
        <li>เปิดใบ ตรวจรายการ ยอด และงบคงเหลือของบรรทัดงบทางขวา</li>
        <li>กด <span class="ui">อนุมัติ</span> เพื่อส่งต่อขั้นถัดไป หรือ <span class="ui">ไม่อนุมัติ</span> พร้อมเหตุผล</li>
    </x-manual.steps>
    <ul>
        <li>อนุมัติครบทุกขั้น เงินถูก<b>ผูกพัน</b>กับงบบรรทัดนั้น ผู้ขอได้รับแจ้งเตือน</li>
        <li>ไม่อนุมัติหรือผู้ขอยกเลิก เงินที่กันไว้คืนเป็นงบคงเหลือทันที</li>
        <li>ผู้รับผิดชอบโครงการขอเองจะข้ามขั้นของตัวเอง</li>
    </ul>
    <x-manual.callout type="note">เฟสนี้จบที่การอนุมัติและผูกพันงบ การออกใบสั่งซื้อ ตรวจรับพัสดุ (รับเข้าคลังวัสดุ/ขึ้นทะเบียนครุภัณฑ์) และเบิกจ่ายเงิน จะตามมาในเฟสถัดไป</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="close" title="ปิดโครงการ">
    <p>เมื่อดำเนินการเสร็จ เปิดหน้าโครงการ กด <span class="ui">ปิดโครงการ</span> ใส่สรุปผล ปิดแล้วขอซื้อ/ขอจ้างเพิ่มไม่ได้ ต้องไม่มีใบที่รออนุมัติค้างอยู่ เปิดใหม่ได้ถ้าจำเป็น</p>
</x-manual.section>
