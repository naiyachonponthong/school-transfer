<p>คุมเงินของโรงเรียนตั้งแต่แผนจนถึงการตัดงบ: ประเภทเงินของปีงบประมาณ → โครงการ → กิจกรรม → คำขอใช้งบ → พิจารณา → ตัดงบ ทุกใบตัดยอดจากงบของกิจกรรม จึงรู้เสมอว่าแต่ละกิจกรรมเหลือเงินประเภทไหนเท่าไร</p>

<x-manual.section anchor="terms" title="คำที่ใช้">
    <ul>
        <li><b>ปีงบประมาณ</b>: 1 ตุลาคม – 30 กันยายน เรียกตามปี พ.ศ. ของเดือนกันยายน</li>
        <li><b>ประเภทเงิน</b>: เงินอุดหนุน เงินกิจกรรมพัฒนาผู้เรียน เงินบำรุงการศึกษา เงินรายได้สถานศึกษา (เพิ่มประเภทอื่นได้)</li>
        <li><b>กิจกรรม</b>: งานย่อยของโครงการ งบอยู่ที่ระดับนี้ แยกตามประเภทเงิน</li>
        <li><b>รอพิจารณา</b>: คำขอที่ยื่นแล้วยังไม่ผ่านครบทุกขั้น เงินถูกกันไว้ ใบอื่นจะขอซ้อนจนเกินงบไม่ได้</li>
        <li><b>ตัดงบแล้ว</b>: คำขอผ่านครบทุกขั้น เจ้าหน้าที่ตัดงบระบุแล้วว่าตัดจากประเภทเงินใดเท่าไร</li>
        <li><b>คงเหลือ</b> = งบ − ตัดงบแล้ว − รอพิจารณา</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="setup" title="ตั้งประเภทเงิน โครงการ และกิจกรรม (งานแผน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">งบประมาณ</span> กด <span class="ui">สร้าง 4 ประเภทมาตรฐาน</span> แล้วกดรูปดินสอใส่วงเงินที่ได้รับของแต่ละประเภท</li>
        <li>เมนู <span class="ui">โครงการ</span> → <span class="ui">ตั้งโครงการ</span> ใส่ชื่อ ผู้รับผิดชอบ หน่วยงาน และ<b>กลุ่ม</b> (กลุ่มทั่วไป / ห้องเรียนพิเศษ) ระบบออกรหัสโครงการให้</li>
        <li>ในหน้าโครงการ กด <span class="ui">เพิ่มกิจกรรม</span> ใส่ชื่อกิจกรรมและงบของแต่ละประเภทเงิน</li>
    </x-manual.steps>
    <x-manual.go route="budget.index">เปิดหน้างบประมาณ</x-manual.go>
    <ul>
        <li>จัดสรรให้กิจกรรมรวมกันเกินวงเงินของประเภทเงินไม่ได้ และลดงบต่ำกว่ายอดที่ตัดแล้วและรอพิจารณาไม่ได้</li>
        <li>กลุ่มของโครงการกำหนดว่าเจ้าหน้าที่ตัดงบกลุ่มไหนเป็นผู้ตัดงบของโครงการนั้น</li>
        <li>หน้างบประมาณตั้ง <b>ขั้นพิจารณา</b> ได้: ผู้ตรวจสอบเอกสาร → รองผู้อำนวยการ → ผู้อำนวยการ ติ๊กเฉพาะขั้นที่โรงเรียนใช้ ขั้นตัดงบมีเสมอ</li>
        <li>ผู้พิจารณาแต่ละขั้นกำหนดด้วยสิทธิ์ของตำแหน่งงาน ดูที่<x-manual.link to="roles">ตำแหน่งงานและสิทธิ์</x-manual.link></li>
    </ul>
</x-manual.section>

<x-manual.section anchor="signature" title="ลายเซ็นของผู้พิจารณา">
    <p>ผู้พิจารณาทุกขั้นต้องมีลายเซ็นในระบบก่อนจึงอนุมัติได้ เซ็นครั้งเดียวที่ เมนูรูปโปรไฟล์ → <span class="ui">ข้อมูลส่วนตัว</span> → การ์ด <span class="ui">ลายเซ็นของฉัน</span> เซ็นด้วยนิ้ว เมาส์ หรือปากกา แล้วกด <span class="ui">บันทึกลายเซ็น</span></p>
    <x-manual.go route="profile">เปิดหน้าข้อมูลส่วนตัว</x-manual.go>
    <p>เมื่ออนุมัติ ระบบเก็บสำเนาลายเซ็น ณ ตอนนั้นไว้กับเอกสาร เซ็นใหม่ภายหลังเอกสารเดิมไม่เปลี่ยน</p>
</x-manual.section>

<x-manual.section anchor="request" title="เขียนคำขอใช้งบ (ครูทุกคน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ขอใช้งบ</span> → <span class="ui">เขียนคำขอใช้งบ</span></li>
        <li>เลือก <b>กิจกรรม</b> ระบบบอกงบคงเหลือ แล้วเลือกประเภทคำขอ: ขอซื้อ/จ้าง · ขอเบิกเงิน · ขอยืมเงิน</li>
        <li>ใส่เรื่อง เหตุผล แล้วเพิ่มรายการพร้อมจำนวนและราคาต่อหน่วย ยอดรวมคิดให้เอง</li>
        <li>กด <span class="ui">ยื่นคำขอ</span> ผู้พิจารณาขั้นแรกได้รับแจ้งเตือน</li>
    </x-manual.steps>
    <x-manual.go route="budget-requests.create">เขียนคำขอใช้งบ</x-manual.go>
    <ul>
        <li>ยอดรวมเกินงบคงเหลือของกิจกรรมจะยื่นไม่ได้</li>
        <li>ติดตามสถานะและดูว่ารอใครอยู่ได้ในหน้าคำขอ ยกเลิกเองได้ตราบที่ยังพิจารณาไม่ครบ</li>
        <li>กด <span class="ui">พิมพ์บันทึกข้อความ</span> เพื่อพิมพ์ใบพร้อมลายเซ็นของขั้นที่อนุมัติแล้ว</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="approve" title="พิจารณาและตัดงบ">
    <x-manual.steps>
        <li>เมนู <span class="ui">ขอใช้งบ</span> ส่วน <span class="ui">รอคุณพิจารณา</span> แสดงใบที่ถึงขั้นของคุณ (ตัวเลขบนเมนูคือจำนวนใบ)</li>
        <li>เปิดใบ ตรวจรายการ ยอด และงบคงเหลือของกิจกรรมทางขวา</li>
        <li>กด <span class="ui">อนุมัติและลงนาม</span> เพื่อส่งต่อขั้นถัดไป หรือ <span class="ui">ไม่อนุมัติ</span> พร้อมเหตุผล</li>
        <li><b>เจ้าหน้าที่ตัดงบ</b> (ขั้นสุดท้าย): ใส่ยอดที่ตัดจากแต่ละประเภทเงิน รวมต้องเท่ายอดคำขอ แล้วกด <span class="ui">ตัดงบและลงนาม</span></li>
    </x-manual.steps>
    <ul>
        <li>ใบเดียวตัดได้หลายประเภทเงิน แต่ละประเภทตัดได้ไม่เกินงบคงเหลือของประเภทนั้นในกิจกรรม</li>
        <li>ไม่อนุมัติหรือผู้ขอยกเลิก เงินที่กันไว้คืนเป็นงบคงเหลือทันที</li>
        <li>โครงการกลุ่มห้องเรียนพิเศษ ตัดงบได้เฉพาะผู้มีสิทธิ์ตัดงบห้องเรียนพิเศษ</li>
    </ul>
    <x-manual.callout type="note">รอบนี้จบที่การตัดงบ การเสนอโครงการ แผนกลยุทธ์และตัวชี้วัด การคืนเงินยืม/ล้างหนี้ ข้อมูลจัดซื้อและการส่งเอกสารการเงิน และรายงานสรุปผลโครงการ จะตามมาในรอบถัดไป</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="close" title="ปิดโครงการ">
    <p>เมื่อดำเนินการเสร็จ เปิดหน้าโครงการ กด <span class="ui">ปิดโครงการ</span> ใส่สรุปผล ปิดแล้วขอใช้งบเพิ่มไม่ได้ ต้องไม่มีคำขอที่รอพิจารณาค้างอยู่ เปิดใหม่ได้ถ้าจำเป็น</p>
</x-manual.section>
