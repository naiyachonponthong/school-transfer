<p>จัดสอบคัดเลือกนักเรียนเข้าใหม่ครบวงจร: จัดห้องสอบและเลขประจำตัวสอบอัตโนมัติ พิมพ์เอกสารห้องสอบ ตรวจกระดาษคำตอบด้วยกล้องมือถือ รวมคะแนนหลายวิชา (ถ่วงน้ำหนักได้) จัดอันดับ และประกาศผลให้ผู้สมัครดูออนไลน์ — ทำทีละ<b>รอบสอบต่อระดับชั้น</b> ตามขั้นตอน 1–4</p>
