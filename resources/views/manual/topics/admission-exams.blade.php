<x-manual.section anchor="rooms" title="1. ห้องสอบ / ผู้เข้าสอบ">
    <x-manual.steps>
        <li>เมนู <span class="ui">รับสมัครนักเรียน</span> → <span class="ui">สอบคัดเลือก</span> → เปิดชั้นที่จะสอบ (เช่น ม.1) ใส่ <b>วันสอบ</b></li>
        <li><b>ห้องสอบ:</b> บรรทัดละห้อง <code>ชื่อห้อง, จำนวนที่นั่ง</code> เช่น <code>321, 30</code> · <code>หอประชุม, 60</code></li>
        <li><b>เลขประจำตัวสอบคนแรก</b> (เช่น 10001) และ <b>เรียงเลขตาม</b>: ลำดับการสมัคร หรือ ชื่อ (ก–ฮ)</li>
        <li>กดจัด ระบบให้เลขประจำตัวสอบ ห้องสอบ และเลขที่นั่งทุกคน · <span class="ui">จัดใหม่ทั้งหมด</span> ถ้าต้องเปลี่ยน</li>
    </x-manual.steps>
    <ul>
        <li>ผู้ที่ <b>ค้างค่าสมัคร</b> ยังไม่มีสิทธิ์สอบ จะไม่ได้เลข — ยืนยันสลิปแล้วกดจัดอีกครั้ง ผู้ที่ได้เลขแล้วเลขไม่เปลี่ยน</li>
        <li>พิมพ์เอกสาร (ทั้งหมด หรือ <span class="ui">พิมพ์เฉพาะห้อง</span>): <b>รายชื่อติดหน้าห้องสอบ · ใบลงชื่อเข้าสอบ · บัตรติดโต๊ะสอบ</b></li>
    </ul>
</x-manual.section>

<x-manual.section anchor="subjects" title="2. วิชาสอบ + เฉลย">
    <x-manual.steps>
        <li>ทางขวา <span class="ui">เพิ่มวิชาสอบ</span>: ชื่อวิชา (เช่น คณิตศาสตร์) จำนวนข้อ <b>น้ำหนัก (×)</b> (เช่น คณิต ×2)</li>
        <li>แต่ละวิชามีปุ่ม <span class="ui">เฉลย</span> · <span class="ui">กระดาษคำตอบ</span> · <span class="ui">สแกน</span> · <span class="ui">ผลตรวจ</span> — ใช้หน้าเดียวกับ <x-manual.link to="exams">ตรวจข้อสอบด้วยมือถือ</x-manual.link></li>
        <li>ใส่เฉลยให้ครบ (ป้าย <span class="badge bg-success">เฉลยครบ</span>) แล้วพิมพ์<b>กระดาษคำตอบรายบุคคล</b> ที่พิมพ์ชื่อและระบายเลขประจำตัวสอบไว้แล้ว</li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="scan" title="3. สแกนตรวจ">
    <p>หลังสอบ เปิด <span class="ui">สแกน</span> ของแต่ละวิชาบนมือถือ สแกนกระดาษทีละแผ่น (หลายเครื่องพร้อมกันได้) ตรวจทานแผ่นที่ระบบไม่แน่ใจให้ครบ — ตัวเลข "ตรวจแล้ว" ของแต่ละวิชาบอกความคืบหน้า</p>
</x-manual.section>

<x-manual.section anchor="rank" title="4. จัดอันดับ / ประกาศผล">
    <x-manual.steps>
        <li><b>เกณฑ์คัดเลือก:</b> จำนวนรับ · จำนวนสำรอง · คะแนนรวมขั้นต่ำ (ไม่บังคับ) · ข้อความท้ายประกาศ → <span class="ui">บันทึกเกณฑ์ (ดูผลในตารางทันที)</span></li>
        <li>ตารางอันดับเรียงตาม<b>คะแนนรวมถ่วงน้ำหนัก</b> คะแนนเท่ากันดูคะแนนวิชาตามลำดับที่เพิ่ม แล้วจึงดูเลขที่ใบสมัคร ผลเป็น ผ่าน / สำรอง / ไม่ผ่าน / ขาดสอบ</li>
        <li>ตรวจ <span class="ui">ก่อนประกาศผล</span> (แผ่นรอตรวจทาน เฉลยครบ) แล้วกด <span class="ui">ประกาศผล</span> — สถานะใบสมัครเปลี่ยนตามผล ผู้สมัครเห็นคะแนน อันดับ และผลในหน้าสถานะ</li>
        <li><span class="ui">พิมพ์ประกาศรายชื่อ</span> (ผู้ผ่านและสำรอง) · <span class="ui">พิมพ์รายงานคะแนน</span> · <span class="ui">ส่งออก Excel</span></li>
    </x-manual.steps>
    <x-manual.callout type="warn">ประกาศแล้วพบข้อผิดพลาด (เช่น เฉลยผิด): กด <span class="ui">ยกเลิกประกาศ</span> แก้ไข แล้วประกาศใหม่ — ระบบคำนวณคะแนนและอันดับใหม่ให้ทั้งหมด</x-manual.callout>
</x-manual.section>
