<p>ทำตามลำดับนี้ก่อนให้ครูและผู้ปกครองเริ่มใช้ เพราะหลายเมนูต้องใช้ข้อมูลจากขั้นก่อนหน้า (เช่น เช็คชื่อต้องมีห้องและนักเรียน กรอกคะแนนต้องเปิดรายวิชา) ใช้เวลาประมาณครึ่งวันถึงหนึ่งวัน</p>

<x-manual.section anchor="checklist" title="เช็กลิสต์ 10 ขั้น">
    <x-manual.steps>
        <li><b>ตั้งค่าโรงเรียน</b> — ชื่อ ที่อยู่ สังกัด โลโก้ ผู้อำนวยการและผู้ลงนามในเอกสาร เวลามาสาย เวลาแต่ละคาบ <br><x-manual.link to="settings" /></li>
        <li><b>ปีการศึกษา / ภาคเรียน</b> — เพิ่มภาคเรียนปัจจุบันแล้วกด <span class="ui">ตั้งเป็นปัจจุบัน</span> ทุกหน้าในระบบใช้ภาคเรียนนี้เป็นค่าเริ่มต้น <br><x-manual.link to="year" /></li>
        <li><b>ห้องเรียน</b> — สร้างห้องทุกชั้น (สร้างหลายห้องพร้อมกันได้) แล้วกำหนดครูประจำชั้น</li>
        <li><b>รายวิชาในหลักสูตร</b> — รหัสวิชา ชื่อ ประเภท (พื้นฐาน/เพิ่มเติม/กิจกรรม) หน่วยกิต ชั่วโมง กลุ่มสาระ</li>
        <li><b>บัญชีครูและบุคลากร</b> — เพิ่มทีละคน กำหนดบทบาท ครูจะต้องตั้งรหัสผ่านใหม่เองตอนเข้าครั้งแรก <br><x-manual.link to="users" /></li>
        <li><b>นักเรียน</b> — นำเข้าจาก Excel โดยคัดลอก-วาง ระบบสร้างห้องที่ยังไม่มีและบัญชีผู้ปกครองจากเบอร์โทรให้อัตโนมัติ <br><x-manual.link to="students" /></li>
        <li><b>เปิดรายวิชา</b> — จับคู่ วิชา × ห้อง × ครูผู้สอน (เลือกหลายห้อง หลายวิชาพร้อมกันได้) <br><x-manual.link to="gradebook" /></li>
        <li><b>ตารางเรียน</b> — จัดคาบรายห้อง ระบบเตือนครูสอนชนกัน (ใช้กับเช็คชื่อรายคาบและหน้าแรกของครู) <br><x-manual.link to="timetable" /></li>
        <li><b>LINE Official Account</b> — ตั้งค่าเพื่อแจ้งเตือนผู้ปกครองและครู แล้วแจ้งทุกคนให้เชื่อม LINE <br><x-manual.link to="line" /></li>
        <li><b>สำรองข้อมูลอัตโนมัติ</b> — ให้ผู้ดูแลเครื่องตั้ง Task Scheduler/cron แล้วตรวจว่าเมนูสำรองข้อมูลมีไฟล์เกิดขึ้นทุกคืน <br><x-manual.link to="backup" /></li>
    </x-manual.steps>
</x-manual.section>

