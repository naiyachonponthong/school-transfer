<x-manual.section anchor="grades" title="ผลการเรียนและเวลาเรียน">
    <ul>
        <li><b>ผลการเรียน</b> — เกรดรายวิชา เกรดเฉลี่ย และผลสอบที่ครูเปิดให้ดู</li>
        <li><b>การมาเรียน</b> — สรุปมา/ขาด/ลา/สาย และเวลาเรียนรายวิชา ถ้าวิชาไหนต่ำกว่า 80% จะมีป้าย <span class="badge bg-danger">มส.</span> เตือนให้รีบคุยกับครูผู้สอน</li>
        <li><b>ความประพฤติ</b> — คะแนนคงเหลือและบันทึกที่ครูบันทึก</li>
        <li><b>ปพ.1</b> — ระเบียนแสดงผลการเรียนของตัวเอง</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="more" title="ค่าเทอม ใบลา หนังสือขออนุญาต แบบประเมินตนเอง">
    <ul>
        <li><b>เลือกชุมนุม</b> — ในช่วงที่โรงเรียนเปิดรับ เลือกได้ 1 ชุมนุม เห็นจำนวนที่เหลือ เปลี่ยนได้จนกว่าจะปิดรับ</li>
        <li><b>ค่าเทอม</b> — ดูรายการใบแจ้งหนี้และยอดค้างของตัวเองได้อย่างเดียว การชำระเงินและแนบสลิปทำโดยผู้ปกครอง</li>
        <li><b>ใบลา</b> — ดูใบลาที่ผู้ปกครองส่งและผลการอนุมัติของครู นักเรียนส่งใบลาเองไม่ได้</li>
        <li><b>หนังสือขออนุญาต</b> — อ่านหนังสือจากโรงเรียนและดูว่าผู้ปกครองตอบแล้วหรือยัง ถ้ายังช่วยแจ้งผู้ปกครองด้วย</li>
        <li><b>แบบประเมินตนเอง</b> — ถ้าโรงเรียนเปิดแบบประเมินให้นักเรียนตอบ จะขึ้นในเมนูนี้ ตอบครบทุกข้อแล้วกดบันทึก แก้คำตอบได้ภายในภาคเรียน</li>
        <li><b>สุขภาพ</b> — น้ำหนัก ส่วนสูง และประวัติการมาห้องพยาบาล</li>
    </ul>
</x-manual.section>

