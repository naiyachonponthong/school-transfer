        <li><b>วิธีที่ 1 (แนะนำ):</b> เลือกตารางใน Excel/Google Sheets ทั้งหมด <kbd>Ctrl</kbd>+<kbd>C</kbd> แล้ววางในช่อง <kbd>Ctrl</kbd>+<kbd>V</kbd> · <b>วิธีที่ 2:</b> อัปโหลดไฟล์ CSV</li>
        <li>กด <span class="ui">นำเข้า</span></li>
    </x-manual.steps>
    <x-manual.go route="students.import">เปิดหน้านำเข้า</x-manual.go>
    <ul>
        <li>ห้องที่ยังไม่มีในปีการศึกษานี้ ระบบสร้างให้อัตโนมัติ</li>
        <li>ใส่เบอร์ผู้ปกครองไว้ ระบบสร้างบัญชีผู้ปกครองให้ (ชื่อผู้ใช้ = เบอร์ · รหัสผ่าน = 6 หลักท้าย) พี่น้องเบอร์เดียวกันผูกบัญชีเดียวกัน</li>
        <li>รหัสนักเรียนที่มีอยู่แล้ว = อัปเดตข้อมูล ไม่สร้างซ้ำ</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="add" title="เพิ่ม / แก้ไขนักเรียนทีละคน">
    <x-manual.steps>
        <li>เมนู <span class="ui">นักเรียน</span> → <span class="ui">เพิ่มนักเรียน</span> (หรือเปิดนักเรียนแล้วกด <span class="ui">แก้ไข</span>)</li>
        <li><b>ข้อมูลหลัก</b> (จำเป็น: รหัส ชื่อ นามสกุล) ห้อง เลขที่ ชื่อเล่น เพศ วันเกิด สถานะ</li>
        <li><b>ข้อมูลสำหรับ ปพ.1</b> — เลขประจำตัวประชาชน สัญชาติ เชื้อชาติ ศาสนา ชื่อบิดา-มารดา วันเข้าเรียน โรงเรียนเดิม จังหวัด ชั้นเดิม (กรอกทีหลังได้ แต่ต้องครบก่อนพิมพ์ ปพ.1)</li>
        <li><b>ผู้ปกครอง</b> — ชื่อและเบอร์โทร ระบบสร้างบัญชีให้ทันที · <b>รูปถ่าย</b> · <b>สุขภาพ</b> (กรุ๊ปเลือด โรคประจำตัว/แพ้ยา)</li>
        <li>กด <span class="ui">บันทึก</span> หรือ <span class="ui">บันทึกแล้วเพิ่มคนต่อไป</span></li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="profile" title="หน้าข้อมูลนักเรียน">
    <p>ค้นหาด้วย <kbd>Ctrl</kbd>+<kbd>K</kbd> หรือคลิกชื่อในรายชื่อห้อง จะเห็นทุกอย่างของนักเรียนคนนั้นในหน้าเดียว: ข้อมูลส่วนตัว ผู้ปกครอง บัญชีนักเรียน ประวัติการมาเรียน ผลการเรียนและ GPA บันทึกพฤติกรรม สุขภาพ ใบแจ้งหนี้</p>
    <p>ปุ่มด้านบน: <span class="ui">ปพ.1</span> <span class="ui">ปพ.7</span> <span class="ui">สมุดพก</span> <span class="ui">แฟ้มผลงาน</span> <span class="ui">ส่งข้อความผู้ปกครอง</span> <span class="ui">แก้ไข</span> และ <i class="bi bi-clock-history"></i> ประวัติการแก้ไขของนักเรียนคนนี้ (ผู้ดูแล)</p>
</x-manual.section>

<x-manual.section anchor="guardians" title="จัดการผู้ปกครอง">
    <ul>
        <li>การ์ด <span class="ui">ผู้ปกครอง</span> ในหน้าข้อมูลนักเรียน → เพิ่มผู้ปกครองอีกคน (เช่น พ่อและแม่ใช้คนละบัญชี) หรือนำผู้ปกครองออก</li>
        <li>เปลี่ยนเบอร์ผู้ปกครอง: แก้ที่หน้าผู้ใช้งาน (ผู้ดูแลระบบ) เพราะเบอร์เป็นชื่อผู้ใช้เข้าระบบ</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="status" title="ย้ายออก / ลาออก / จบการศึกษา">
    <p>แก้ไขนักเรียน → เปลี่ยน <b>สถานะ</b> และกรอกวันที่จบ/ออกและสาเหตุ (ใช้ใน ปพ.1/ปพ.7) <b>อย่าลบ</b> — ระบบไม่ยอมให้ลบนักเรียนที่มีคะแนน การมาเรียน หรือเอกสารแล้ว เพื่อให้ออกเอกสารย้อนหลังได้เสมอ</p>
</x-manual.section>

