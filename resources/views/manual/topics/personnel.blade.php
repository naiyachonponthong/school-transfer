        <li>เพิ่มประวัติการอบรม/พัฒนาตนเอง (เรื่อง หน่วยงาน วันที่ จำนวนชั่วโมง)</li>
    </x-manual.steps>
    <x-manual.go route="staff.index">เปิดทะเบียนบุคลากร</x-manual.go>
    <ul>
        <li>บุคลากรเปิดและแก้ข้อมูลของตัวเองได้ ฝ่ายบุคคลเห็นและแก้ได้ทุกคน</li>
        <li>ระบบเตือนล่วงหน้าเมื่อใบอนุญาตประกอบวิชาชีพใกล้หมดอายุ (ต้องตั้งเวลารันคำสั่งประจำวันของระบบไว้ ดูหัวข้อสำหรับผู้ดูแลเครื่องเซิร์ฟเวอร์)</li>
    </ul>
