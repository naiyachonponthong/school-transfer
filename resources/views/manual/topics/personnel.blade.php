        <li>ผู้รับเปิดอ่านแล้วกด <span class="ui">รับทราบ</span> เจ้าหน้าที่เห็นว่าใครรับทราบแล้วบ้าง</li>
    </x-manual.steps>
    <x-manual.go route="office.index">เปิดหน้าสารบรรณ</x-manual.go>
    <p>เลขทะเบียนออกให้อัตโนมัติเรียงตามปี ไม่ซ้ำกันแม้ลงทะเบียนพร้อมกันหลายคน</p>
</x-manual.section>

<x-manual.section anchor="directory" title="ทะเบียนติดต่อ">
    <p>เมนู <span class="ui">ทะเบียนติดต่อ</span> แสดงครูและบุคลากรทุกคนเป็นการ์ด: รูป ชื่อ ตำแหน่ง หน่วยงาน เบอร์โทร (กดโทรได้) ค้นด้วยชื่อ ตำแหน่ง รหัส หรือเบอร์ และกรองตามหน่วยงานได้ ครูและบุคลากรทุกคนเปิดดูได้ ผู้ปกครองและนักเรียนไม่เห็นหน้านี้</p>
    <x-manual.go route="staff.directory">เปิดทะเบียนติดต่อ</x-manual.go>
    <x-manual.callout type="note">หน้านี้แสดงเฉพาะข้อมูลติดต่อ ไม่แสดงเลขบัตร วันเกิด หรือที่อยู่ · ไม่อยากให้แสดงเบอร์โทร เปิด <span class="ui">ไม่แสดงเบอร์โทรในทะเบียนติดต่อ</span> ที่หน้า <span class="ui">ประวัติของฉัน</span></x-manual.callout>
</x-manual.section>

<x-manual.section anchor="org" title="โครงสร้างองค์กร">
    <p>เมนู <span class="ui">โครงสร้างองค์กร</span> แสดงผังหน่วยงานของโรงเรียน หัวหน้า และจำนวนคนของแต่ละหน่วย สลับดูเป็นตารางและสั่งพิมพ์ได้ บุคลากรทุกคนดูได้</p>
    <x-manual.steps>
        <li>(ฝ่ายบุคคล) ครั้งแรกกด <span class="ui">สร้างโครงสร้างมาตรฐาน</span> ได้ผู้อำนวยการ 4 ฝ่ายบริหาร และกลุ่มสาระการเรียนรู้ แล้วแก้ชื่อ เพิ่ม หรือลบให้ตรงกับโรงเรียน</li>
        <li>กดรูปดินสอที่หน่วยงานเพื่อกำหนดหัวหน้า ย้ายไปอยู่ใต้หน่วยอื่น และติ๊กรายชื่อบุคลากรในหน่วย</li>
        <li>ครูหนึ่งคนอยู่ได้หลายหน่วย เช่น กลุ่มสาระและงานของฝ่าย เลือก <b>หน่วยหลัก</b> ได้ที่หน้าประวัติของคนนั้น</li>
    </x-manual.steps>
    <x-manual.go route="org.index">เปิดโครงสร้างองค์กร</x-manual.go>
    <x-manual.callout type="tip"><b>รหัสบุคลากร</b> กำหนดได้ที่หน้าประวัติของแต่ละคน หรือกด <span class="ui">ออกรหัสอัตโนมัติ</span> ที่หน้าทะเบียนบุคลากร รหัสนี้ใช้เป็นรหัสบุคคลในเครื่องสแกนที่ประตูได้เหมือนรหัสนักเรียน</x-manual.callout>
</x-manual.section>
