<p>ช่องทางสื่อสาร 3 แบบ: <b>ข้อความ</b> (แชทส่วนตัวครู–ผู้ปกครอง) · <b>ฟีดข่าว</b> (ข่าวกิจกรรมและประกาศเกียรติคุณแบบโซเชียล) · <b>ประกาศ</b> (เรื่องทางการถึงกลุ่มเป้าหมาย พร้อมนับจำนวนคนอ่าน) ทุกช่องทางแจ้งเตือนทาง LINE ได้</p>

<x-manual.section anchor="chat" title="ข้อความ (แชทครู–ผู้ปกครอง)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ข้อความ</span> (ผู้ปกครอง: <span class="ui">คุยกับครู</span>) → <span class="ui">แชทใหม่</span></li>
        <li><b>ครู:</b> เลือกนักเรียน ระบบเปิดห้องแชทกับผู้ปกครองทุกคนของนักเรียนคนนั้น · <b>ผู้ปกครอง:</b> เลือกบุตรหลาน แล้วเลือกครู (ครูประจำชั้นหรือครูผู้สอนของลูกเท่านั้น)</li>
        <li>กด <span class="ui">เริ่มแชท</span> พิมพ์ข้อความ หรือแนบรูป (เช่น ใบรับรองแพทย์ การบ้าน)</li>
    </x-manual.steps>
    <x-manual.go route="chat.index">เปิดข้อความ</x-manual.go>
    <ul>
        <li>ห้องแชท<b>ผูกกับนักเรียน</b> — ข้อมูลนักเรียนแสดงด้านข้าง ครูไม่ต้องจำว่าผู้ปกครองคนนี้เป็นของใคร</li>
        <li>ข้อความใหม่ขึ้นเองทุก ~4 วินาทีขณะเปิดหน้าแชท · ตัวเลขแดงที่เมนู = ยังไม่ได้อ่าน</li>
        <li>แจ้งเตือน LINE ไปยังอีกฝ่าย <b>ไม่เกินทุก 10 นาที</b>ต่อห้อง (กันข้อความรัว) — คุยต่อเนื่องได้ในหน้าแชท</li>
        <li>ครูเริ่มแชทจากหน้าข้อมูลนักเรียนได้ด้วยปุ่ม <span class="ui">ส่งข้อความผู้ปกครอง</span></li>
    </ul>
    <x-manual.callout type="note">ครูเห็นเฉพาะนักเรียนที่ตนเป็นครูประจำชั้นหรือสอนอยู่ · ผู้ปกครองคุยได้เฉพาะครูของลูกตนเอง เพื่อความเป็นส่วนตัวของทุกฝ่าย</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="feed" title="ฟีดข่าว">
    <x-manual.steps>
        <li>เมนู <span class="ui">ฟีดข่าว</span> → กล่อง <span class="ui">สร้างโพสต์</span> (ครูและผู้ดูแล)</li>
        <li>เลือกชนิด: <span class="ui">ข่าวสาร</span> (กิจกรรม บรรยากาศ) หรือ <span class="ui">ประกาศเกียรติคุณ</span> (ใส่ชื่อรางวัล/ผลงาน และเลือกนักเรียน — ไม่บังคับ)</li>
        <li>เล่าเรื่องราว และ <span class="ui">แนบรูป</span> (1 รูป ไม่เกิน 6 MB)</li>
        <li><b>ใครเห็นได้:</b> ทุกคน · ผู้ปกครอง · ครูและบุคลากร · เฉพาะห้อง (เลือกห้อง)</li>
        <li>กด <span class="ui">โพสต์</span></li>
    </x-manual.steps>
    <x-manual.go route="feed.index">เปิดฟีดข่าว</x-manual.go>
    <ul>
        <li>ทุกคนกด<b>ส่งกำลังใจ</b>ใต้โพสต์ได้</li>
        <li>รางวัลที่ครูบันทึกใน <x-manual.link to="portfolio">แฟ้มผลงาน</x-manual.link> แชร์มาเป็นประกาศเกียรติคุณได้อัตโนมัติ · ประกาศใหม่ก็ขึ้นในฟีดด้วย</li>
        <li>ลบโพสต์: เมนู ⋯ ที่โพสต์ → <span class="ui">ลบโพสต์</span> (เจ้าของโพสต์และผู้ดูแล)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="announcements" title="ประกาศ">
    <x-manual.steps>
        <li>เมนู <span class="ui">ประกาศ</span> → <span class="ui">สร้างประกาศ</span></li>
        <li>ใส่ <b>หัวข้อ</b> และ <b>รายละเอียด</b></li>
        <li><b>ส่งถึง:</b> ผู้ดูแลเลือกได้ ทุกคน · ผู้ปกครองทั้งหมด · ครูและบุคลากร · เฉพาะห้องเรียน — ครูทั่วไปส่งได้เฉพาะห้องที่ตนเป็นครูประจำชั้น หรือถึงครูและบุคลากร</li>
        <li>ผู้ดูแลติ๊ก <span class="ui">ปักหมุดไว้ด้านบน</span> สำหรับเรื่องสำคัญได้ → บันทึก — ผู้รับได้แจ้งเตือนทาง LINE</li>
    </x-manual.steps>
    <x-manual.go route="announcements.index">เปิดประกาศ</x-manual.go>
    <ul>
        <li>ครูเห็น <i class="bi bi-eye"></i> <b>อ่านแล้ว … คน</b> ของแต่ละประกาศ ผู้รับที่ยังไม่อ่านเห็นป้าย <b>ใหม่</b></li>
        <li>แก้ไข/ลบได้เฉพาะผู้สร้างและผู้ดูแลระบบ</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="which" title="ใช้ช่องทางไหนดี">
    <ul>
        <li>เรื่องของนักเรียน<b>คนเดียว</b> → <b>ข้อความ</b></li>
        <li>เรื่องทางการที่ต้องรู้ว่า<b>ใครอ่านแล้ว</b> (เลื่อนสอบ ประชุมผู้ปกครอง) → <b>ประกาศ</b></li>
        <li>ภาพกิจกรรม ข่าวดี รางวัล → <b>ฟีดข่าว</b></li>
        <li>วันสำคัญที่ต้องจำ (วันหยุด สอบ) → <x-manual.link to="calendar">ปฏิทิน</x-manual.link></li>
    </ul>
</x-manual.section>
