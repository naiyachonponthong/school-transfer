    <x-manual.steps>
        <li>เมนู <span class="ui">ผู้ใช้งาน</span> → <span class="ui">เพิ่มผู้ใช้</span></li>
        <li>เลือก <b>บทบาท</b>: ผู้ดูแลระบบ / ครู / ผู้ปกครอง</li>
        <li>กรอกชื่อ-สกุล ตำแหน่ง (พิมพ์ในรายงานและเอกสาร) <b>ชื่อผู้ใช้</b> เบอร์โทร (เข้าระบบด้วยเบอร์ได้) อีเมล</li>
        <li>ตั้งรหัสผ่านชั่วคราว แล้วกด <span class="ui">บันทึก</span> — แจ้งชื่อผู้ใช้และรหัสชั่วคราวให้เจ้าตัว ระบบจะบังคับให้ตั้งรหัสใหม่ตอนเข้าครั้งแรก</li>
    </x-manual.steps>
    <x-manual.go route="users.create" admin>เพิ่มผู้ใช้</x-manual.go>
    <x-manual.callout type="note">ให้สิทธิ์ผู้ดูแลระบบเฉพาะคนที่จำเป็น (ผู้บริหาร ฝ่ายวิชาการ ฝ่ายทะเบียน การเงิน) เพราะเห็นและแก้ได้ทุกอย่าง</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="parents" title="บัญชีผู้ปกครอง">
    <ul>
        <li>ปกติ <b>ไม่ต้องสร้างเอง</b> — ระบบสร้างให้อัตโนมัติจากเบอร์โทรผู้ปกครองตอนเพิ่ม/นำเข้านักเรียน หรือตอนมอบตัวจากใบสมัคร ชื่อผู้ใช้ = เบอร์โทร รหัสผ่านเริ่มต้น = 6 หลักท้ายเบอร์</li>
        <li>พี่น้องที่ใช้เบอร์ผู้ปกครองเดียวกันจะผูกกับบัญชีเดียวกันเอง</li>
        <li>เพิ่ม/นำผู้ปกครองออกจากนักเรียนแต่ละคนได้ที่หน้าข้อมูลนักเรียน → การ์ด <span class="ui">ผู้ปกครอง</span></li>
        <li>สร้างบัญชีผู้ปกครองด้วยมือ: เลือกบทบาทผู้ปกครองแล้วเลือก <b>บุตรหลาน</b> ในฟอร์ม</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="reset" title="รีเซ็ตรหัสผ่าน">
    <x-manual.steps>
        <li>หน้า <span class="ui">ผู้ใช้งาน</span> ค้นหาชื่อ แล้วกดปุ่มกุญแจ <i class="bi bi-key"></i> ท้ายแถว</li>
        <li>ระบบแสดงรหัสผ่านใหม่ <b>ครั้งเดียว</b> (ผู้ปกครอง = 6 หลักท้ายเบอร์ · คนอื่น = รหัสสุ่ม 8 ตัว) จดหรือแจ้งเจ้าตัวทันที</li>
        <li>เจ้าตัวเข้าระบบด้วยรหัสนี้ แล้วต้องตั้งรหัสใหม่เอง</li>
    </x-manual.steps>
    <x-manual.callout type="tip">ผู้ใช้ที่เชื่อม LINE แล้วรีเซ็ตเองได้จากลิงก์ <span class="ui">ลืมรหัสผ่าน?</span> ในหน้าเข้าสู่ระบบ ไม่ต้องรอผู้ดูแล</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="students" title="บัญชีนักเรียน">
    <x-manual.steps>
        <li>ครูประจำชั้นเปิดเมนู <span class="ui">นักเรียน</span> เลือกห้อง แล้วกด <span class="ui">สร้างบัญชีนักเรียนห้องนี้</span></li>
        <li>ระบบสร้างบัญชีให้ทุกคนที่ยังไม่มี: ชื่อผู้ใช้ = รหัสนักเรียน รหัสผ่านสุ่ม</li>
        <li>หน้า <span class="ui">ใบแจกรหัสผ่านนักเรียน</span> แสดงรหัสผ่าน<b>ครั้งเดียวเท่านั้น</b> กด <span class="ui">พิมพ์ใบแจก</span> ตัดแจกนักเรียนก่อนออกจากหน้า</li>
        <li>นักเรียนลืมรหัส: ครูเปิดหน้าข้อมูลนักเรียนคนนั้น → การ์ด <span class="ui">บัญชีนักเรียน</span> → <span class="ui">รีเซ็ตรหัสผ่าน</span></li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="leave" title="ครูย้าย / ลาออก">
    <p>เปิดฟอร์มผู้ใช้แล้วปิดสวิตช์ <span class="ui">เปิดใช้งาน</span> แทนการลบ เพื่อให้ประวัติ (คะแนนที่กรอก การเช็คชื่อ เอกสารที่ลงนาม) ยังอ้างถึงชื่อเดิมได้ แล้วเปลี่ยนครูผู้สอนในรายวิชาและครูประจำชั้นให้คนใหม่</p>
</x-manual.section>

