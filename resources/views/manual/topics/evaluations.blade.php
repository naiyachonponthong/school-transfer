<p>ครูประจำชั้นประเมิน <b>คุณลักษณะอันพึงประสงค์ 8 ประการ</b> และ <b>การอ่าน คิดวิเคราะห์ และเขียน</b> ของนักเรียนทั้งห้องในตารางเดียว ผลที่บันทึกถูกนำไปพิมพ์ใน <x-manual.link to="documents">ปพ.1 และสมุดรายงานผล (ปพ.6)</x-manual.link> อัตโนมัติ</p>

<x-manual.section anchor="who" title="ใครประเมินได้">
    <ul>
        <li><b>ครูประจำชั้น</b> และ <b>ครูประจำชั้นร่วม</b> ของห้องนั้น เห็นเฉพาะห้องของตัวเอง</li>
        <li><b>ผู้ดูแลระบบ</b> เลือกได้ทุกห้อง (เช่น กรอกแทนครูที่ย้ายไปแล้ว)</li>
        <li>ถ้าขึ้นข้อความ "ไม่มีห้องที่คุณเป็นครูประจำชั้น" ให้ผู้ดูแลตั้งครูประจำชั้นที่ <x-manual.link to="year">ห้องเรียน</x-manual.link> ก่อน</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="fill" title="กรอกผลการประเมิน">
    <x-manual.steps>
        <li>เมนู <span class="ui">คุณลักษณะ / อ่านคิดเขียน</span> เลือก <b>ภาคเรียน</b> และ <b>ห้องเรียน</b></li>
        <li>แต่ละคนเลือกระดับในแต่ละข้อ: <b>3</b> ดีเยี่ยม · <b>2</b> ดี · <b>1</b> ผ่าน · <b>0</b> ไม่ผ่าน (ชี้ที่หัวคอลัมน์เพื่อดูชื่อข้อเต็ม)</li>
        <li><b>ตั้งทั้งคอลัมน์ในครั้งเดียว:</b> แถวสีเทา <span class="ui">ตั้งทุกคนในคอลัมน์</span> ใต้หัวตาราง เลือกระดับ เช่น 3 แล้วทุกคนในข้อนั้นเป็น 3 — จากนั้นค่อยแก้เฉพาะบางคน</li>
        <li>คอลัมน์ <b>สรุป</b> คำนวณให้ทันทีเมื่อประเมินครบ 8 ข้อ</li>
        <li>คอลัมน์สุดท้ายคือ <b>อ่าน คิดวิเคราะห์ และเขียน</b> (ระดับเดียวกัน)</li>
        <li>กด <span class="ui">บันทึก</span></li>
    </x-manual.steps>
    <x-manual.go route="evaluations.index">เปิดหน้าประเมิน</x-manual.go>
    <x-manual.callout type="tip">วิธีเร็วที่สุด: ตั้งทั้งคอลัมน์เป็น <b>3</b> ทุกข้อ แล้วไล่แก้เฉพาะนักเรียนที่ต้องปรับระดับ ห้อง 40 คนใช้เวลาไม่ถึง 5 นาที</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="rule" title="เกณฑ์สรุปคุณลักษณะ (หลักสูตรแกนกลางฯ 2551)">
    <ul>
        <li><b>ดีเยี่ยม</b> — ได้ดีเยี่ยม 5–8 ข้อ และไม่มีข้อใดต่ำกว่าดี</li>
        <li><b>ดี</b> — ได้ดีเยี่ยม 1–4 ข้อหรือได้ดีทั้งหมด และไม่มีข้อใดต่ำกว่าดี หรือได้ดีขึ้นไป 5–7 ข้อ และไม่มีข้อใดต่ำกว่าผ่าน</li>
        <li><b>ผ่าน</b> — ได้ผ่านทั้ง 8 ข้อ หรือได้ดีขึ้นไป 1–4 ข้อ และไม่มีข้อใดต่ำกว่าผ่าน</li>
        <li><b>ไม่ผ่าน</b> — มีข้อใดข้อหนึ่งไม่ผ่าน</li>
    </ul>
    <x-manual.callout type="note">เกณฑ์จบการศึกษาในหน้า <x-manual.link to="documents">ปพ.3 อนุมัติผู้จบ</x-manual.link> ใช้ผลประเมิน<b>ภาคเรียนล่าสุด</b> — ถ้ายังไม่ได้ประเมิน หรือผลสรุป "ไม่ผ่าน" นักเรียนคนนั้นจะยังไม่ผ่านเกณฑ์ ครูประจำชั้นควรประเมินให้ครบก่อนสิ้นปี</x-manual.callout>
</x-manual.section>
