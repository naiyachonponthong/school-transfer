        <li>มีข้อมูลนักเรียน ผลรายภาค/รายปี สรุปรายกลุ่มสาระ หน่วยกิต กิจกรรม คุณลักษณะ อ่านคิดเขียน ผลการตัดสิน และ GPAX</li>
        <li>กด <span class="ui">พิมพ์ / บันทึก PDF</span></li>
    </x-manual.steps>
    <x-manual.callout type="warn"><b>ปพ.1 ฉบับจริง</b> ต้องพิมพ์ลงแบบพิมพ์ของกระทรวงที่มี <b>ชุดที่/เลขที่</b> — หลังพิมพ์ ให้ผู้ดูแลกรอกชุดที่ เลขที่ และหมายเหตุ ในกล่อง <span class="ui">ทะเบียนคุมแบบพิมพ์ ปพ.1 ฉบับจริง</span> แล้วกด <span class="ui">บันทึกการออกฉบับจริง</span> เลขจะพิมพ์ลงเอกสารฉบับถัดไปและเก็บในทะเบียนคุม</x-manual.callout>
    <p>ผู้ปกครองและนักเรียนเปิดดู ปพ.1 (ฉบับสำเนา) ของตัวเองได้จากเมนูของตน</p>
