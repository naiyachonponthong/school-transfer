</x-manual.section>

<x-manual.section anchor="qr" title="สติกเกอร์ QR">
    <ul>
        <li>กรองรายการตามสถานที่/ประเภท แล้วกด <span class="ui">พิมพ์สติกเกอร์ QR</span> (หรือ <span class="ui">สติกเกอร์</span> ในหน้าครุภัณฑ์ชิ้นเดียว)</li>
        <li>สติกเกอร์มีเลขครุภัณฑ์ ชื่อ และ QR พร้อมข้อความ "สแกนเพื่อแจ้งซ่อม" — ครูทุกคนสแกนด้วยกล้องมือถือแล้วกด <span class="ui">แจ้งซ่อม</span> ได้ทันที (ครูทั่วไปเห็นเฉพาะข้อมูลพื้นฐาน ไม่เห็นมูลค่า)</li>
        <li>พิมพ์ A4 ขนาดจริง 100%</li>
    </ul>
