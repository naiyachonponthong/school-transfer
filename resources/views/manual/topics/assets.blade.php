        <li><b>เลขครุภัณฑ์และชื่อ:</b> ประเภท · ชื่อครุภัณฑ์ · ยี่ห้อ/รุ่น · หมายเลขเครื่อง (Serial) · <b>เลขครุภัณฑ์ — เว้นว่าง = ออกเลขอัตโนมัติ</b> (ช่องแสดงเลขถัดไปให้ดู)</li>
        <li><b>มูลค่าและค่าเสื่อมราคา:</b> ราคาต่อชิ้น · <b>วันที่ได้มา</b> (ใช้คิดปีงบประมาณในเลขครุภัณฑ์) · แหล่งงบ/วิธีได้มา (เงินงบประมาณ · เงินอุดหนุน · เงินรายได้สถานศึกษา · รับบริจาค) · อายุการใช้งาน (เว้นว่าง = ตามประเภท เช่น คอมพิวเตอร์ 3 ปี อื่น ๆ 5 ปี)</li>
        <li><b>ที่ตั้ง ผู้รับผิดชอบ และสถานะ:</b> สถานที่/ห้อง · ครูผู้รับผิดชอบ · สถานะ · รูปครุภัณฑ์</li>
