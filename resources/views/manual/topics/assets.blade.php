<x-manual.section anchor="numbering" title="ตั้งรูปแบบเลขครุภัณฑ์">
    <p>หน้าครุภัณฑ์ → <span class="ui">รูปแบบเลข</span></p>
    <ul>
        <li>รูปแบบสำเร็จรูป: <code>{CAT}-{FY}-{SEQ}</code> แยกตามประเภท นับใหม่ทุกปีงบประมาณ (ค่าเริ่มต้น เช่น <code>7440-2569-0001</code>) · <code>{CAT}-{SEQ}/{FY}</code> ปีงบไว้ท้าย · <code>สธ.{CAT}-{FY}-{SEQ}</code> มีอักษรย่อโรงเรียนนำหน้า · <code>{FY}-{SEQ5}</code> ไม่แยกประเภท</li>
        <li>ตัวแทน: <code>{CAT}</code> รหัสประเภท · <code>{FY}</code> ปีงบประมาณ พ.ศ. ที่ได้มา (ต.ค.–ก.ย.) · <code>{FY2}</code> ปีงบ 2 หลัก · <code>{YEAR}</code> ปี พ.ศ. · <code>{SEQ}</code> เลขลำดับ 4 หลัก (<code>{SEQ3}</code>–<code>{SEQ6}</code>)</li>
        <li>ตั้ง<b>รหัสประเภท</b>ให้ตรงกับทะเบียนเดิมของโรงเรียน (ค่าเริ่มต้นเป็นตัวอย่างรหัสพัสดุ 4 หลัก เช่น คอมพิวเตอร์ 7440 สำนักงาน 7110)</li>
    </ul>
    <x-manual.callout type="note">ระบบหาเลขลำดับถัดไปจากเลขที่มีอยู่แล้วในทะเบียน — นำเข้าทะเบียนเดิมก่อน แล้วเลขใหม่จะต่อจากเลขเดิมเอง</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="value" title="ค่าเสื่อมราคาและมูลค่าสุทธิ">
