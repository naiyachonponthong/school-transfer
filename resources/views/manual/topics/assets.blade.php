<p>ทะเบียนครุภัณฑ์ของโรงเรียน: เลขครุภัณฑ์อัตโนมัติ ค่าเสื่อมราคาแบบเส้นตรง สติกเกอร์ QR ติดตัวครุภัณฑ์ (ครูสแกนแจ้งซ่อมได้) และ<b>ตรวจสอบพัสดุประจำปี</b>ด้วยกล้องมือถือ — ใช้ได้เฉพาะผู้ดูแลระบบและครูงานพัสดุ</p>

