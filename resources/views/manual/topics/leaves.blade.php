<x-manual.section anchor="flow" title="ใบลาเดินทางอย่างไร">
    <x-manual.steps>
        <li>ผู้ปกครองส่งใบลาจากมือถือ (เลือกลาป่วย/ลากิจ ช่วงวันที่ เหตุผล แนบรูปใบรับรองแพทย์ได้) — <x-manual.link to="parent">คู่มือผู้ปกครอง</x-manual.link></li>
        <li>ครูประจำชั้นเห็นทันทีที่กระดิ่ง หน้าแรก และเมนู <span class="ui">ใบลานักเรียน</span> (ได้ LINE ถ้าเชื่อมไว้)</li>
        <li>ครูกด <span class="ui">อนุมัติ</span> หรือ <span class="ui">ไม่อนุมัติ</span> (ใส่เหตุผลได้)</li>
        <li>อนุมัติแล้ว <b>ระบบลงเช็คชื่อ "ลากิจ/ลาป่วย" ทุกวันในช่วงที่ลาให้อัตโนมัติ</b> (ข้ามเสาร์-อาทิตย์) และแจ้งผลผู้ปกครองทาง LINE</li>
    </x-manual.steps>
    <x-manual.go route="leaves.index">เปิดหน้าใบลานักเรียน</x-manual.go>
</x-manual.section>

<x-manual.section anchor="review" title="พิจารณาใบลา">
    <ul>
        <li>กด <span class="ui">ดูรายละเอียด</span> เพื่อดูเหตุผลและรูปแนบเต็มจอ ก่อนตัดสินใจ</li>
        <li>อนุมัติจากหน้าแรกได้เลย ไม่ต้องเข้าเมนู</li>
        <li>ใบลาที่พิจารณาแล้วเปลี่ยนผลไม่ได้ ถ้าต้องแก้การมาเรียนให้แก้ที่ <x-manual.link to="attendance">เช็คชื่อ</x-manual.link> วันนั้น</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="phone" title="ผู้ปกครองโทรแจ้งลา (ครูบันทึกแทน)">
    <x-manual.steps>
        <li>หน้า <span class="ui">ใบลานักเรียน</span> → <span class="ui">บันทึกการลา (ผู้ปกครองโทรแจ้ง)</span></li>
        <li>พิมพ์รหัสหรือชื่อนักเรียน เลือกประเภท ช่วงวันที่ และเหตุผล</li>
        <li>กด <span class="ui">บันทึกและอนุมัติ</span> — ระบบอนุมัติและลงเช็คชื่อให้ทันที</li>
    </x-manual.steps>
</x-manual.section>
