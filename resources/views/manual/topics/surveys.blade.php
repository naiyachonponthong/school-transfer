<p>ใช้ในระบบดูแลช่วยเหลือนักเรียน: สร้างแบบคัดกรอง/แบบประเมินพฤติกรรม ให้ครูหรือผู้ปกครองตอบ ระบบรวมคะแนน<b>รายด้าน</b>และแปลผล (เช่น ปกติ / เสี่ยง / มีปัญหา) ให้อัตโนมัติ พร้อมสรุปทั้งห้อง</p>

<x-manual.section anchor="answer" title="ครูประเมินนักเรียน">
    <x-manual.steps>
        <li>เมนู <span class="ui">แบบประเมิน</span> ที่การ์ดของแบบประเมิน เลือกห้อง → <span class="ui">ประเมิน</span></li>
        <li>ตารางสรุปทั้งห้องแสดงผลรายด้านของแต่ละคน (สีเขียว/เหลือง/แดงตามเกณฑ์) กด <span class="ui">ประเมิน</span> ท้ายแถวของนักเรียน (ประเมินแล้วจะเป็นปุ่ม <span class="ui">แก้ไข</span>)</li>
        <li>ตอบครบทุกข้อ → <span class="ui">บันทึกผลการประเมิน</span> กลับมาที่ตารางห้องเพื่อทำคนถัดไป</li>
    </x-manual.steps>
    <x-manual.go route="surveys.index">เปิดหน้าแบบประเมิน</x-manual.go>
    <ul>
        <li>ครูเลือกได้เฉพาะห้องที่เป็นครูประจำชั้น/ครูประจำชั้นร่วม ผู้ดูแลเลือกได้ทุกห้อง</li>
        <li>นับผลแยกตาม<b>ภาคเรียน</b> — ประเมินซ้ำภาคถัดไปเพื่อดูพัฒนาการได้</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="parent" title="ให้ผู้ปกครองตอบ">
    <p>แบบที่ตั้งผู้ตอบเป็น <b>ผู้ปกครองประเมิน</b> หรือ <b>ครูและผู้ปกครอง</b> จะไปขึ้นที่หน้าผู้ปกครอง → บุตรหลาน → แท็บ <span class="ui">แบบประเมิน</span> ครูกด <span class="ui">ดูผล (ผู้ปกครองตอบ)</span> เพื่อดูผลรายห้อง</p>
</x-manual.section>

<x-manual.section anchor="student" title="ให้นักเรียนประเมินตนเอง">
    <p>แบบที่ตั้งผู้ตอบเป็น <b>นักเรียนประเมินตนเอง</b> หรือ <b>ครู ผู้ปกครอง และนักเรียน</b> จะไปขึ้นที่เมนู <span class="ui">แบบประเมินตนเอง</span> ของนักเรียน นักเรียนตอบได้เฉพาะของตัวเอง ผลรวมที่นักเรียนประเมินจะแสดงในคอลัมน์ <b>นักเรียน</b> ของตารางรายห้อง เทียบกับผลที่ครูและผู้ปกครองประเมินได้</p>
</x-manual.section>

