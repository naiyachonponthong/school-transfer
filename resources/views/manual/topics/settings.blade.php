<x-manual.section anchor="theme" title="สีธีมของระบบ">
    <p>เลือกสีหลักสีเดียว ระบบคำนวณเฉดอ่อน/เข้มให้ทั้งระบบเอง (ค่าเริ่มต้นสีส้ม) ควรเลือกสีประจำโรงเรียน</p>
</x-manual.section>

<x-manual.section anchor="school" title="ข้อมูลโรงเรียนและผู้ลงนาม">
    <ul>
        <li><b>ชื่อโรงเรียน / ชื่อย่อ</b> — ชื่อย่อแสดงบนเมนูและหัวเอกสารที่พื้นที่น้อย</li>
        <li><b>ที่อยู่ เบอร์โทร สังกัด/เขตพื้นที่ จังหวัด</b> — พิมพ์ลงหัว ปพ.1 ปพ.3 ปพ.7 และเอกสารต่าง ๆ</li>
        <li><b>โลโก้</b> — ใช้บนหน้าเข้าสู่ระบบ บัตรนักเรียน กระดาษคำตอบ ใบเสร็จ และประกาศ</li>
        <li><b>ผู้อำนวยการ · รองผู้อำนวยการฝ่ายวิชาการ · หัวหน้างานวัดผล · นายทะเบียน</b> — ชื่อพิมพ์ในช่องลงนามของสมุดพก ปพ.5 ปพ.1 ปพ.7 และประกาศผลสอบคัดเลือก</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="time" title="เวลาและตารางเรียน">
    <ul>
        <li><b>นักเรียนมาสายหลัง</b> — ใช้กับจุดสแกนหน้าประตู (สแกนหลังเวลานี้ = สาย)</li>
        <li><b>ครูมาสายหลัง</b> — ใช้กับการลงเวลาปฏิบัติงานของครู</li>
        <li><b>จำนวนคาบ/วัน และเวลาแต่ละคาบ</b> (บรรทัดละคาบ เช่น <code>08:30-09:20</code>) — ใช้กับตารางเรียน เช็คชื่อรายคาบ และหน้าแรกของครู</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="payment" title="ช่องทางรับชำระเงิน">
    <p>ใส่ <b>หมายเลขพร้อมเพย์</b> (เบอร์โทรหรือเลขประจำตัวผู้เสียภาษีของบัญชีโรงเรียน) ระบบจะสร้าง QR พร้อมเพย์ที่ใส่ยอดให้ในใบแจ้งหนี้และค่าสมัครอัตโนมัติ และใส่ <b>ข้อมูลบัญชีธนาคาร</b> สำหรับผู้ที่โอนแบบปกติ</p>
    <x-manual.callout type="warn">ตรวจหมายเลขพร้อมเพย์ให้ถูกต้องก่อนใช้จริง ลองสแกนจ่าย 1 บาทจากใบแจ้งหนี้ทดลองดูว่าชื่อบัญชีปลายทางถูกต้อง</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="line" title="LINE Official Account">
    <p>ใส่ Channel access token · Channel secret · LINE ID ของ OA และนำ Webhook URL ไปใส่ใน LINE Developers ช่อง token/secret ปล่อยว่างไว้ = ใช้ค่าเดิม (ระบบไม่แสดงค่าจริงบนหน้าเว็บ) · เลือกเปิด/ปิดการแจ้งผู้ปกครองเมื่อลูกสแกนเข้า-ออก และเมื่อขาด/สาย — ดูขั้นตอนเต็มที่ <x-manual.link to="line" /></p>
</x-manual.section>

<x-manual.section anchor="gate" title="สแกนหน้าประตู และลงเวลาครูด้วย GPS">
    <ul>
        <li><b>สแกนหลังเวลานี้ = กลับบ้าน</b> — โหมดอัตโนมัติของจุดสแกน: ก่อนเวลานี้นับเป็นมาโรงเรียน หลังเวลานี้นับเป็นกลับบ้าน</li>
        <li><b>ครูต้องอยู่ในรัศมีโรงเรียนจึงลงเวลาได้</b> + ละติจูด/ลองจิจูดโรงเรียน + รัศมี (เมตร) — กด <span class="ui">ใช้ตำแหน่งปัจจุบัน</span> ขณะอยู่ที่โรงเรียนเพื่อเติมพิกัดให้ รัศมีแนะนำ 200–500 เมตร (ไม่เปิดบังคับ = ลงเวลาได้ทุกที่ และถ้ามือถืออนุญาตให้ใช้ตำแหน่ง ระบบจะเก็บระยะห่างไว้ในรายงาน)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="other" title="ห้องสมุด รับสมัคร และงานพัสดุ">
    <ul>
        <li><b>ระยะยืมหนังสือ (วันทำการ)</b> — ค่าเริ่มต้นของกำหนดคืนตอนยืม</li>
        <li><b>รับสมัคร</b> — ปุ่มไปหน้า <span class="ui">ตั้งค่าฟอร์มรับสมัคร</span> (ช่วงเปิดรับ ชั้นที่รับ คำถาม ค่าสมัคร)</li>
        <li><b>ครูที่จัดการครุภัณฑ์ ตรวจสอบพัสดุ และรับเรื่องแจ้งซ่อม</b> — เลือกได้หลายคน (กด <kbd>Ctrl</kbd> ค้างแล้วคลิก) คนที่เลือกจะเห็นเมนูคลังวัสดุ ครุภัณฑ์ ตรวจสอบพัสดุ อนุมัติการจอง และได้ LINE เมื่อมีแจ้งซ่อม/ใบเบิกใหม่</li>
        <li>ปุ่ม <span class="ui">ตั้งรูปแบบเลขครุภัณฑ์อัตโนมัติ</span> และ <span class="ui">ตั้งรูปแบบรหัสวัสดุอัตโนมัติ</span> — <x-manual.link to="assets" /> · <x-manual.link to="supplies" /></li>
    </ul>
</x-manual.section>

