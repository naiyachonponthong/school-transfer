<x-manual.section anchor="numbering" title="ตั้งรูปแบบบาร์โค้ด / เลขทะเบียน">
    <p>หน้าห้องสมุด → ปุ่ม <i class="bi bi-gear"></i> → <span class="ui">รูปแบบบาร์โค้ด</span> (ค่าเริ่มต้น <code>B{SEQ8}</code>) หรือ <span class="ui">รูปแบบเลขทะเบียน</span> (ค่าเริ่มต้น <code>{SEQ5}</code>) ใช้ตัวแทน <code>{YEAR}</code> (ปี พ.ศ.) <code>{SEQ5}</code> (เลขลำดับ 5 หลัก) ได้ เช่น <code>{YEAR}-{SEQ4}</code> = 2569-0001 · รูปแบบบาร์โค้ดใช้ได้เฉพาะตัวอักษรภาษาอังกฤษ ตัวเลข และเครื่องหมาย (ห้ามภาษาไทย) เพื่อให้เครื่องยิงอ่านได้ · เปลี่ยนรูปแบบแล้วมีผลกับเล่มที่ลงทะเบียนใหม่เท่านั้น</p>
    <ul>
        <li>ย้ายข้อมูลจากระบบเดิม: ถ้ามีเล่มที่ยังไม่มีเลขทะเบียน เมนูเดียวกันจะมี <span class="ui">ออกเลขทะเบียนให้เล่มที่ยังไม่มี</span> (เรียงตามลำดับที่ลงระบบ)</li>
    </ul>
