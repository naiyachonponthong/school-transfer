<x-manual.section anchor="copies" title="จัดการตัวเล่ม">
    <p>หน้าหนังสือ → ตาราง <span class="ui">ตัวเล่ม</span> แสดง ฉบับที่ บาร์โค้ด เลขทะเบียน ชั้นจัดเก็บ สถานะ (ว่าง/ถูกยืม) และ<b>สภาพ</b></p>
    <ul>
        <li>สภาพ: <b>ดี · พอใช้ · ชำรุด</b> (ยังยืมได้) · <b>ส่งซ่อม · สูญหาย · จำหน่ายออก</b> (ยืมไม่ได้)</li>
        <li>หนังสือหายหรือจำหน่าย ให้<b>เปลี่ยนสภาพ</b> อย่าลบ เพื่อเก็บประวัติ · ปุ่ม <span class="ui">ลบเล่มนี้</span> ใช้กับเล่มที่บันทึกผิดและไม่เคยถูกยืมเท่านั้น</li>
        <li>เล่มที่มีป้าย <span class="badge bg-warning text-dark">ยังไม่พิมพ์ป้าย</span> จะอยู่ในคิวพิมพ์ป้าย</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="labels" title="พิมพ์ป้ายสัน · บาร์โค้ดปกนอก · บาร์โค้ดปกใน">
    <x-manual.steps>
        <li>หน้าห้องสมุด → <span class="ui">พิมพ์ป้าย</span> (ตัวเลขแดง = จำนวนเล่มที่ยังไม่ได้พิมพ์)</li>
        <li><b>ชนิดป้าย:</b>
            <ul>
                <li><b>ป้ายสันหนังสือ</b> 2.5 × 4 ซม. — เลขเรียกหนังสือเรียงบรรทัด ติดสันล่าง</li>
                <li><b>บาร์โค้ดปกนอก</b> 5 × 2.5 ซม. — สำหรับยิงยืม-คืน ติดปกหลัง</li>
                <li><b>บาร์โค้ดปกใน</b> 7 × 4 ซม. — บาร์โค้ด + ชื่อเรื่อง เลขทะเบียน ราคา ติดด้านในปก (สำรองกรณีป้ายนอกหลุด)</li>
                <li><b>ครบชุด (3 แบบ)</b> — แยกหน้าให้ทีละชนิด</li>
            </ul>
        </li>
        <li><b>เล่มที่จะพิมพ์:</b> <span class="ui">ยังไม่ได้พิมพ์</span> (คิว) · <span class="ui">ช่วงเลขทะเบียน</span> เช่น 00001–00050 · จากหน้าหนังสือพิมพ์เฉพาะเล่มนั้น/เล่มที่เลือก</li>
        <li>ตัวเลือก: <span class="ui">เว้นช่องแรก</span> (ใช้กระดาษสติกเกอร์ที่ใช้ไปบางส่วนแล้ว) · <span class="ui">แถบสีตามหมวดบนป้ายสัน</span> · <span class="ui">เส้นขอบสำหรับตัด</span></li>
        <li>กดพิมพ์ แล้วเมื่อติดป้ายเสร็จ กด <span class="ui">ติดป้ายครบแล้ว (เอาออกจากคิว)</span></li>
    </x-manual.steps>
