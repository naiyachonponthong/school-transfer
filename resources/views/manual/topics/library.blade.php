<x-manual.section anchor="circulation" title="ยืม-คืน">
    <x-manual.steps>
        <li>หน้าห้องสมุด → <span class="ui">ยืม-คืน</span></li>
        <li><b>ยืม:</b> ช่องนักเรียน สแกนบัตรนักเรียนหรือพิมพ์รหัส → ช่องหนังสือ ยิง<b>บาร์โค้ดปกนอก</b> (หรือพิมพ์เลขทะเบียน/ISBN) → <span class="ui">ยืม</span> · ช่องนักเรียนค้างไว้ ยิงเล่มถัดไปต่อได้เลย</li>
        <li><b>คืน:</b> ช่อง <span class="ui">สแกนบาร์โค้ดหนังสือที่คืน</span> ยิงบาร์โค้ด → <span class="ui">คืน</span> (หรือกด <span class="ui">รับคืน</span> ในรายการที่ถูกยืม)</li>
    </x-manual.steps>
    <ul>
        <li>กำหนดคืนนับเป็น<b>วันทำการ</b> ตามที่ตั้งใน <span class="ui">ตั้งค่า → ระยะยืมหนังสือ</span> (ค่าเริ่มต้น 7 วัน)</li>
        <li>ระบบไม่ให้ยืม: หนังสืออ้างอิง (ใช้ในห้องสมุดเท่านั้น) · เล่มที่ส่งซ่อม/สูญหาย/จำหน่าย · เล่มที่ยังไม่คืน · นักเรียนที่มีหนังสือเกินกำหนดค้างอยู่</li>
        <li>ปุ่ม <span class="ui">แจ้งเกินกำหนด</span> ส่ง LINE ถึงผู้ปกครองของนักเรียนทุกคนที่มีหนังสือเกินกำหนด</li>
    </ul>
