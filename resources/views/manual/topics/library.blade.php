<p>ลงรายการหนังสือตามหลักบรรณารักษ์สากล: ข้อมูลบรรณานุกรม · เลขหมู่<b>ระบบทศนิยมของดิวอี้ (DDC)</b> · เลขผู้แต่ง · <b>ทะเบียนตัวเล่ม</b> (หนังสือชื่อเดียวกันหลายเล่ม แต่ละเล่มมีบาร์โค้ดและเลขทะเบียนของตัวเอง) · พิมพ์<b>ป้ายสัน บาร์โค้ดปกนอก บาร์โค้ดปกใน</b> · ยืม-คืนด้วยเครื่องยิงบาร์โค้ด</p>

<x-manual.section anchor="terms" title="ศัพท์ที่ควรรู้">
    <ul>
        <li><b>ระเบียนหนังสือ</b> = ข้อมูลของหนังสือ 1 ชื่อเรื่อง (ชื่อเรื่อง ผู้แต่ง ISBN เลขหมู่) · <b>ตัวเล่ม</b> = หนังสือแต่ละเล่มที่มีจริงบนชั้น</li>
        <li><b>บาร์โค้ด</b> (เช่น <code>B00000015</code>) — ติดตัวเล่ม ใช้ยิงยืม-คืน ไม่ซ้ำกันทั้งห้องสมุด</li>
        <li><b>เลขทะเบียน</b> (เช่น <code>00015</code>) — เลขลงทะเบียนรับหนังสือ เรียงตามลำดับที่รับเข้า</li>
        <li><b>เลขเรียกหนังสือ</b> = สัญลักษณ์หมวด (ถ้ามี) + <b>เลขหมู่ DDC</b> + <b>เลขผู้แต่ง</b> + ล./ฉ. เช่น <code>591.5 ส412ก ล.2 ฉ.3</code> พิมพ์ลงป้ายสันเพื่อเรียงบนชั้น</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="add" title="ลงทะเบียนหนังสือใหม่">
    <x-manual.steps>
        <li>เมนู <span class="ui">ห้องสมุด</span> → <span class="ui">ลงทะเบียนหนังสือ</span></li>
        <li><b>ข้อมูลบรรณานุกรม:</b> ชื่อเรื่อง · <b>ผู้แต่ง</b> (คนไทย: ชื่อ นามสกุล ไม่ต้องใส่คำนำหน้า นาย/นาง/ดร. · ต่างชาติ: Surname, Firstname) · ผู้แต่งร่วม/ผู้แปล · ISBN · สำนักพิมพ์ สถานที่พิมพ์ ปีพิมพ์ ครั้งที่พิมพ์ จำนวนหน้า ความสูง ภาษา ชื่อชุด หัวเรื่อง สาระสังเขป และภาพปก</li>
        <li><b>ประเภททรัพยากร:</b> หนังสือทั่วไป · นวนิยาย (น) · เรื่องสั้น (รส) · หนังสือเด็กและเยาวชน (ย) · หนังสืออ้างอิง (อ — ไม่ให้ยืมออก) · แบบเรียน (บร) · นวนิยายภาษาอังกฤษ (Fic)</li>
        <li><b>เลขหมู่:</b> เลือก <span class="ui">หมวดใหญ่</span> (000–900) → <span class="ui">หมวดย่อย</span> ระบบเติมเลขให้ แล้วใส่ทศนิยมละเอียดขึ้นได้ เช่น 590 → 591.5 (มีรายการเลขหมู่ที่ใช้บ่อยให้เลือก เช่น 294.3 พระพุทธศาสนา, 959.3 ประวัติศาสตร์ไทย) — นวนิยาย/เรื่องสั้นไม่ต้องใส่เลขหมู่</li>
        <li><b>เลขผู้แต่ง:</b> ระบบเติม<b>อักษรตัวแรกผู้แต่ง</b>และ<b>อักษรตัวแรกชื่อเรื่อง</b>ให้ ใส่<b>เลขจากตารางเลขผู้แต่ง</b> (ไทย / Cutter-Sanborn) ตรงกลางถ้าห้องสมุดใช้ เช่น ส + 412 + ก = <code>ส412ก</code></li>
        <li>หนังสือชุดหลายเล่ม ติ๊ก <span class="ui">หนังสือชุดหลายเล่ม</span> และใส่ <b>เล่มที่ (ล.)</b> · ดู<b>ตัวอย่างป้ายสัน</b>ด้านขวาก่อนบันทึก</li>
        <li><b>ตัวเล่มที่รับเข้า:</b> จำนวนเล่ม วันที่ได้รับ วิธีได้มา (จัดซื้อ / ได้รับบริจาค / งบประมาณ / โครงการ / แลกเปลี่ยน) ราคา/เล่ม ชั้นจัดเก็บ — ระบบออก<b>บาร์โค้ดและเลขทะเบียน</b>เรียงต่อกันให้ทุกเล่ม</li>
        <li>กด <span class="ui">บันทึก</span> หรือ <span class="ui">บันทึกแล้วลงทะเบียนเล่มถัดไป</span></li>
    </x-manual.steps>
