<x-manual.section anchor="record" title="บันทึกคะแนนความประพฤติ">
    <p>นักเรียนทุกคนเริ่มต้นที่ <b>100 คะแนน</b> บันทึกเพิ่ม (คำชม) หรือหัก (พฤติกรรมไม่เหมาะสม) ได้</p>
    <x-manual.steps>
        <li>เมนู <span class="ui">ความประพฤติ</span> เลือกห้อง</li>
        <li>ติ๊กเลือกนักเรียน <b>ได้หลายคน</b> (หรือ <span class="ui">เลือกทั้งห้อง</span>)</li>
        <li>กดปุ่มหัวข้อพฤติกรรม เช่น "มาสาย −5" "ช่วยงานโรงเรียน +5" — บันทึกให้ทุกคนที่เลือกในครั้งเดียว</li>
        <li>พิมพ์ <b>หมายเหตุ</b> เพิ่มได้ (เช่น รายละเอียดเหตุการณ์) — หัวข้อใหม่ให้ผู้ดูแลเพิ่มในหน้าตั้งค่า</li>
    </x-manual.steps>
    <x-manual.go route="behavior.index">เปิดหน้าความประพฤติ</x-manual.go>
</x-manual.section>

