<p>บุคลากรแต่ละคนถือ<b>ตำแหน่งงาน</b>ได้หลายตำแหน่ง แต่ละตำแหน่งกำหนดว่าทำอะไรได้บ้าง เมนูและปุ่มในระบบจะแสดงตามสิทธิ์ที่มี</p>

<x-manual.section anchor="assign" title="กำหนดตำแหน่งให้บุคลากร">
    <x-manual.steps>
        <li>เมนู <span class="ui">ผู้ใช้งาน</span> → เปิดผู้ใช้ที่ต้องการ</li>
        <li>ที่หัวข้อ <b>ตำแหน่งงาน</b> ติ๊กตำแหน่งที่ถือ (เลือกได้หลายตำแหน่ง) → <span class="ui">บันทึก</span></li>
    </x-manual.steps>
    <x-manual.go route="users.index">เปิดรายชื่อผู้ใช้</x-manual.go>
    <ul>
        <li>ไม่ติ๊กตำแหน่งใดเลย = ได้สิทธิ์ของตำแหน่ง "ครู"</li>
        <li><b>ผู้ดูแลระบบ</b>มีทุกสิทธิ์เสมอ</li>
        <li>ผู้ปกครองและนักเรียนไม่ใช้ตำแหน่งงาน</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="edit" title="ปรับสิทธิ์ของตำแหน่ง / สร้างตำแหน่งใหม่">
    <x-manual.steps>
        <li>เปิดเมนู <span class="ui">ตำแหน่งและสิทธิ์</span> จะเห็นตารางสิทธิ์ แถว = สิทธิ์ คอลัมน์ = ตำแหน่ง</li>
        <li>ติ๊กหรือเอาออกตามต้องการ → <span class="ui">บันทึก</span></li>
        <li>สร้างตำแหน่งของโรงเรียนเองได้ เช่น หัวหน้ากลุ่มสาระ แล้วติ๊กสิทธิ์ให้</li>
    </x-manual.steps>
    <x-manual.go route="roles.index">เปิดตำแหน่งงานและสิทธิ์</x-manual.go>
    <ul>
        <li>ตำแหน่งที่ระบบสร้างมาให้ลบไม่ได้ แต่ปรับสิทธิ์ได้</li>
        <li>สิทธิ์แยกเป็นกลุ่ม เช่น วิชาการ การเงิน (ดูอย่างเดียว / จัดการ) บุคคล รับสมัคร ดูแลช่วยเหลือ สารบรรณ ผู้บริหาร ตั้งค่า</li>
    </ul>
    <x-manual.callout type="tip">กระดิ่งแจ้งเตือนก็แยกตามสิทธิ์: สลิปรอตรวจขึ้นเฉพาะผู้มีสิทธิ์จัดการการเงิน ใบลาบุคลากรขึ้นเฉพาะฝ่ายบุคคล ใบสมัครใหม่ขึ้นเฉพาะฝ่ายรับสมัคร</x-manual.callout>
</x-manual.section>
