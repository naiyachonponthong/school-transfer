<p>ออกใบแจ้งหนี้ค่าธรรมเนียมทั้งห้องในครั้งเดียว ผู้ปกครองเห็นยอดในมือถือ สแกน <b>QR พร้อมเพย์</b> จ่ายแล้วส่งสลิป งานการเงินตรวจสลิปและออกใบเสร็จ — ครูเปิดดูสถานะการชำระได้ (ออกใบแจ้งหนี้และรับเงินได้เฉพาะผู้ดูแลระบบ)</p>

<x-manual.section anchor="before" title="ตั้งค่าก่อนเริ่ม">
    <p><span class="ui">ตั้งค่า</span> → ช่องทางชำระเงิน: <b>หมายเลขพร้อมเพย์</b> (เบอร์โทรหรือเลขประจำตัวผู้เสียภาษีของบัญชีโรงเรียน — ใช้สร้าง QR ที่ล็อกยอดเงินให้อัตโนมัติ) และ <b>บัญชีธนาคาร</b> — ดู <x-manual.link to="settings" /></p>
</x-manual.section>

<x-manual.section anchor="create" title="ออกใบแจ้งหนี้">
    <x-manual.steps>
        <li>เมนู <span class="ui">ค่าธรรมเนียม</span> → <span class="ui">ออกใบแจ้งหนี้</span></li>
        <li>ใส่ <b>ชื่อใบแจ้งหนี้</b> (เช่น ค่าธรรมเนียมการศึกษา ภาคเรียนที่ 2/2569) · <b>ภาคเรียน</b> · <b>กำหนดชำระ</b></li>
        <li><b>รายการ:</b> ชื่อรายการ + จำนวนเงิน (บาท/คน) กด <span class="ui">เพิ่มรายการ</span> ได้หลายบรรทัด เช่น ค่าอาหารกลางวัน ค่าคอมพิวเตอร์ ค่าประกันอุบัติเหตุ</li>
        <li><b>ส่งถึง:</b> <span class="ui">เลือกห้อง</span> (ติ๊กได้หลายห้อง) และ/หรือ ระบุรหัสนักเรียน (เช่น 10001, 10002)</li>
        <li>กด <span class="ui">ออกใบแจ้งหนี้</span> — ระบบสร้างใบแจ้งหนี้แยกรายคน พร้อมเลขที่ และแจ้งผู้ปกครองทาง LINE</li>
    </x-manual.steps>
    <x-manual.go route="invoices.create" admin>ออกใบแจ้งหนี้</x-manual.go>
</x-manual.section>

<x-manual.section anchor="parent-pay" title="ผู้ปกครองชำระเงิน">
    <x-manual.steps>
        <li>ผู้ปกครองเปิดเมนู <span class="ui">ค่าเทอม</span> (หรือลิงก์จาก LINE) → เลือกใบแจ้งหนี้</li>
        <li><span class="ui">สแกนจ่ายด้วยแอปธนาคาร</span> — QR พร้อมเพย์มียอดเงินใส่ไว้แล้ว (บันทึกรูป QR แล้วเปิดในแอปธนาคารได้)</li>
        <li>โอนเสร็จ → <span class="ui">แนบสลิปโอนเงิน</span> ใส่ยอดที่โอน เวลาโอน → <span class="ui">ส่งสลิป</span></li>
    </x-manual.steps>
    <p>จ่ายบางส่วนได้ (ใส่ยอดน้อยกว่ายอดค้าง) สถานะจะเป็น "ชำระบางส่วน"</p>
</x-manual.section>

<x-manual.section anchor="slips" title="ตรวจสลิป (ผู้ดูแลระบบ / การเงิน)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ตรวจสลิป</span> (ตัวเลขแดง = สลิปรอตรวจ)</li>
        <li>เปิดรูปสลิป เทียบยอดและเวลากับรายการเงินเข้าในบัญชีธนาคาร</li>
        <li>ตรงกัน → <span class="ui">ยืนยัน</span> ระบบบันทึกการชำระและออก<b>ใบเสร็จ</b>ให้ทันที · ไม่ตรง → <span class="ui">ไม่ผ่าน</span> พร้อมเหตุผล (ผู้ปกครองได้แจ้งเตือนให้ส่งใหม่)</li>
    </x-manual.steps>
    <x-manual.go route="slips.index" admin>เปิดหน้าตรวจสลิป</x-manual.go>
</x-manual.section>

<x-manual.section anchor="cash" title="รับเงินสด / บันทึกการชำระเอง">
    <x-manual.steps>
        <li>เปิดใบแจ้งหนี้ (ค้นหาด้วยเลขที่หรือชื่อนักเรียน) → การ์ด <span class="ui">รับชำระเงิน</span></li>
        <li>ใส่จำนวนเงิน เลือกวิธี <b>เงินสด / โอนเงิน / พร้อมเพย์</b> หมายเหตุ → <span class="ui">ยืนยันรับชำระ</span></li>
        <li>กด <span class="ui">พิมพ์ใบเสร็จ</span> (มีเลขที่ใบเสร็จ ยอดคงค้างหลังชำระ และช่องลงชื่อผู้รับเงิน)</li>
    </x-manual.steps>
</x-manual.section>

