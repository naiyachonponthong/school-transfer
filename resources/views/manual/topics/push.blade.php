<p>นอกจากแจ้งเตือนทาง LINE แล้ว ระบบส่งแจ้งเตือน<b>เด้งบนมือถือหรือคอมพิวเตอร์</b>ได้โดยไม่ต้องเปิดหน้าเว็บค้างไว้ และเข้าสู่ระบบด้วยบัญชี LINE ได้โดยไม่ต้องพิมพ์รหัสผ่าน</p>

<x-manual.section anchor="device" title="เปิดรับแจ้งเตือนบนอุปกรณ์">
    <x-manual.steps>
        <li>กดรูปโปรไฟล์มุมขวาบน → <span class="ui">ข้อมูลส่วนตัว</span> เลื่อนลงมาที่การ์ด <b>แจ้งเตือนบนอุปกรณ์นี้</b></li>
        <li>กด <span class="ui">เปิดรับแจ้งเตือน</span> แล้วกด <b>อนุญาต</b> เมื่อเบราว์เซอร์ถาม</li>
        <li>กด <span class="ui">ส่งทดสอบ</span> เพื่อดูว่าแจ้งเตือนเด้งจริง</li>
    </x-manual.steps>
    <x-manual.go route="profile">เปิดหน้าข้อมูลส่วนตัว</x-manual.go>
    <ul>
        <li>เปิดได้หลายเครื่อง แต่ละเครื่องต้องกดเปิดเอง · ปิดเฉพาะเครื่องได้ด้วยปุ่ม <span class="ui">ปิดบนเครื่องนี้</span></li>
        <li>ได้ข้อความชุดเดียวกับที่ส่งทาง LINE เช่น บุตรหลานมาถึงโรงเรียน ขาดเรียน ใบแจ้งหนี้ ประกาศ หนังสือขออนุญาต</li>
        <li><b>iPhone / iPad:</b> ต้องติดตั้งแอปลงหน้าจอโฮมก่อน (ปุ่มแชร์ → เพิ่มไปยังหน้าจอโฮม) แล้วเปิดจากไอคอนนั้น</li>
        <li>ถ้าป้ายขึ้นว่า <b>ถูกปิดกั้นในเบราว์เซอร์</b> ให้ไปที่การตั้งค่าเว็บไซต์ของเบราว์เซอร์แล้วอนุญาตการแจ้งเตือนให้เว็บของโรงเรียน</li>
    </ul>
    <x-manual.callout type="note">แจ้งเตือนจะแสดงเนื้อหาเมื่อเครื่องนั้นยังเข้าสู่ระบบอยู่ ถ้าออกจากระบบไปแล้วจะขึ้นเพียงว่า "มีการแจ้งเตือนใหม่"</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="line-login" title="เข้าสู่ระบบด้วย LINE">
    <x-manual.steps>
        <li>เข้าสู่ระบบด้วยรหัสผ่านตามปกติหนึ่งครั้ง → <span class="ui">ข้อมูลส่วนตัว</span> → <span class="ui">เชื่อมด้วยบัญชี LINE</span></li>
        <li>ยืนยันในหน้าของ LINE ระบบจะพากลับมาและขึ้นว่าเชื่อมแล้ว</li>
        <li>ครั้งต่อไปกดปุ่มสีเขียว <span class="ui">เข้าสู่ระบบด้วย LINE</span> ที่หน้าเข้าสู่ระบบได้เลย</li>
    </x-manual.steps>
    <ul>
        <li>บัญชี LINE หนึ่งบัญชีเชื่อมได้กับผู้ใช้เดียว</li>
        <li>ปุ่มนี้จะแสดงเมื่อผู้ดูแลระบบตั้งค่า LINE Login แล้วเท่านั้น</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="admin" title="ตั้งค่า LINE Login (ผู้ดูแลระบบ)">
    <x-manual.steps>
        <li>ใน LINE Developers สร้างช่องประเภท <b>LINE Login</b> ใต้ <b>Provider เดียวกับ LINE OA ของโรงเรียน</b></li>
        <li>คัดลอก <b>Callback URL</b> จากหน้าตั้งค่าของระบบไปใส่ในช่อง LINE Login</li>
        <li>นำ <b>Channel ID</b> และ <b>Channel secret</b> มาใส่ที่หน้าตั้งค่า หัวข้อ <b>เข้าสู่ระบบด้วย LINE</b> → บันทึก</li>
    </x-manual.steps>
    <x-manual.go route="settings">เปิดหน้าตั้งค่า</x-manual.go>
    <x-manual.callout type="warn">ถ้าช่อง LINE Login อยู่คนละ Provider กับ LINE OA รหัสผู้ใช้ LINE จะไม่ตรงกัน การแจ้งเตือนทาง LINE ของคนที่เชื่อมด้วยวิธีนี้จะส่งไม่ถึง</x-manual.callout>
    <p>แจ้งเตือนบนอุปกรณ์ไม่ต้องตั้งค่าอะไร ระบบสร้างกุญแจให้เองครั้งแรกที่มีคนเปิดหน้าข้อมูลส่วนตัว เว็บต้องเปิดผ่าน <b>https</b></p>
</x-manual.section>
