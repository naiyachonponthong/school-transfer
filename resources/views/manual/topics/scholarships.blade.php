<p>ทะเบียนทุนการศึกษาของโรงเรียน: รู้ว่าทุนไหนใครให้ งบเท่าไร ใครได้รับ ใครอนุมัติ และมอบแล้วหรือยัง ทุนที่ลดค่าธรรมเนียมจะถูกหักจากใบแจ้งหนี้ให้เอง</p>

<x-manual.section anchor="create" title="ตั้งทุน (ฝ่ายการเงิน / ผู้บริหาร)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ทุนการศึกษา</span> → <span class="ui">ตั้งทุน</span></li>
        <li>ใส่ชื่อทุน ประเภท ผู้ให้ทุน ปีการศึกษา และ<b>วิธีมอบ</b></li>
        <li>ใส่มูลค่าต่อทุน จำนวนทุน และงบรวม (เว้นว่าง = ไม่จำกัด) ระบบจะไม่ให้อนุมัติเกิน</li>
        <li>กำหนดช่วงวันที่เปิดให้ครูประจำชั้นเสนอชื่อ และเงื่อนไข/คุณสมบัติ</li>
    </x-manual.steps>
    <x-manual.go route="scholarships.index">เปิดหน้าทุนการศึกษา</x-manual.go>
    <ul>
        <li><b>ลดค่าธรรมเนียม</b>: ลดเป็นบาทหรือร้อยละ จากยอดรวมหรือเฉพาะรายการ อนุมัติแล้วระบบสร้างส่วนลดประจำตัวให้ ใบแจ้งหนี้ที่ออกจาก<x-manual.link to="fees">ผังค่าธรรมเนียม</x-manual.link>หลังจากนั้นหักเอง</li>
        <li><b>จ่ายเป็นเงิน/สิ่งของ</b>: มูลค่าเป็นบาท อนุมัติแล้วกด <span class="ui">จ่ายทุน</span> เมื่อมอบเงิน ระบบออกเลขที่และใบสำคัญรับเงินให้ผู้รับเซ็น</li>
    </ul>
    <x-manual.callout type="note">มีผู้ได้รับทุนแล้ว วิธีมอบและมูลค่าต่อทุนจะแก้ไม่ได้ เพราะส่วนลดและยอดที่อนุมัติไปแล้วอ้างค่าเดิม ให้ตั้งทุนใหม่แทน</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="nominate" title="เสนอชื่อ (ครูประจำชั้น)">
    <x-manual.steps>
        <li>เมนู <span class="ui">ทุนการศึกษา</span> เปิดทุนที่ขึ้นว่า "เปิดรับ" อ่านเงื่อนไข</li>
        <li>กด <span class="ui">เสนอชื่อ</span> เลือกนักเรียนในห้องที่คุณเป็นครูประจำชั้น เขียนเหตุผล/คุณสมบัติ</li>
        <li>ติดตามผลในหน้าเดียวกัน ถอนชื่อได้ตราบที่ยังไม่ถูกพิจารณา</li>
    </x-manual.steps>
    <p>ครูเห็นเฉพาะรายชื่อนักเรียนในห้องตัวเอง ผู้ปกครองและนักเรียนยังไม่เห็นว่าถูกเสนอชื่อ จะเห็นเมื่อทุนอนุมัติแล้วเท่านั้น</p>
</x-manual.section>

<x-manual.section anchor="decide" title="พิจารณาและมอบทุน">
    <x-manual.steps>
        <li>เปิดทุน ตารางรายชื่อแสดงเกรดเฉลี่ย (ระหว่างภาคที่ยังไม่ตัดเกรดแสดงร้อยละของคะแนนที่เก็บแล้ว) คะแนนความประพฤติ ร้อยละการมาเรียน และเยี่ยมบ้านแล้วหรือยัง ของแต่ละคนจากข้อมูลในระบบ</li>
        <li>ติ๊กคนที่ต้องการ เลือกผล <span class="ui">อนุมัติให้ทุน</span> / <span class="ui">สำรอง</span> / <span class="ui">ไม่อนุมัติ</span> ใส่หมายเหตุ (เช่น มติที่ประชุม) แล้วบันทึก</li>
        <li>ผู้ได้รับทุนและผู้ปกครองได้รับแจ้งเตือน ทุนลดค่าธรรมเนียมมีผลทันที ทุนจ่ายเป็นเงินให้กด <span class="ui">จ่ายทุน</span> เมื่อมอบแล้ว</li>
        <li>กด <span class="ui">ประกาศรายชื่อ</span> เพื่อพิมพ์ประกาศ หรือ <span class="ui">Excel</span> เพื่อส่งออกทะเบียน</li>
    </x-manual.steps>
    <ul>
        <li>คนที่เป็น <b>สำรอง</b> เลือกแล้วอนุมัติภายหลังได้เมื่อมีทุนว่าง</li>
        <li><b>เพิกถอน</b>ทุนที่อนุมัติแล้วได้ถ้ายังไม่ได้จ่ายเงิน ต้องใส่เหตุผล ส่วนลดที่สร้างจากทุนถูกปิด ใบแจ้งหนี้ที่ออกไปแล้วไม่เปลี่ยน</li>
        <li>ประวัติทุนของนักเรียนแต่ละคนอยู่ในแท็บ <span class="ui">ค่าธรรมเนียม</span> ของหน้าข้อมูลนักเรียน</li>
        <li>ข้อมูลรายได้และรายละเอียดจากแบบเยี่ยมบ้านไม่แสดงในหน้านี้ ผู้มีสิทธิ์เปิดดูได้ที่เมนู<x-manual.link to="care">ดูแลช่วยเหลือ</x-manual.link></li>
    </ul>
</x-manual.section>
