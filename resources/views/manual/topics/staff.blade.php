<p>ครูลงเวลาปฏิบัติงานด้วยมือถือ (ตรวจตำแหน่ง GPS ว่าอยู่ในโรงเรียน) ยื่นใบลาออนไลน์พร้อมไฟล์แนบ ผู้บริหารอนุมัติและดูรายงานการมาทำงานได้ทันที</p>

<x-manual.section anchor="checkin" title="ลงเวลาเข้า-ออกงาน">
    <x-manual.steps>
        <li>เมนู <span class="ui">ลงเวลา</span> (บนมือถือ เปิดจากหน้าแรกได้เลย)</li>
        <li>กด <span class="ui">ลงเวลาเข้างาน</span> → เบราว์เซอร์ถามสิทธิ์ตำแหน่ง ให้กด <b>อนุญาต</b></li>
        <li>ตอนกลับกด <span class="ui">ออกงาน</span></li>
    </x-manual.steps>
    <x-manual.go route="checkin">เปิดหน้าลงเวลา</x-manual.go>
    <ul>
        <li>ลงเวลาหลังเวลาที่ตั้งไว้ (ค่าเริ่มต้น 08:00) = <b>มาสาย</b></li>
        <li>ถ้าโรงเรียนเปิดใช้ GPS ต้องอยู่<b>ในรัศมีโรงเรียน</b> (ค่าเริ่มต้น 300 เมตร) จึงลงเวลาได้ ถ้าอยู่ไกลเกินจะขึ้นว่า "คุณอยู่ห่างจากโรงเรียน … เมตร" · ระบบเก็บระยะห่างไว้ในรายงาน</li>
        <li>วันที่ไม่ได้มาโรงเรียน: กด <span class="ui">ไปราชการ</span> หรือ <span class="ui">ลา</span> พร้อมหมายเหตุ (เช่น ประชุมที่เขต) — ไม่ต้องตรวจตำแหน่ง</li>
        <li>ประวัติ <b>30 วันล่าสุด</b> อยู่ด้านล่างของหน้า</li>
    </ul>
    <x-manual.callout type="warn">กดแล้วขึ้นว่า <b>"ต้องเปิดตำแหน่ง (GPS) ของเครื่องก่อนลงเวลา"</b>: เปิด GPS ของมือถือ และเปิดการตั้งค่าเบราว์เซอร์ → สิทธิ์เว็บไซต์ → ตำแหน่ง → อนุญาต แล้วโหลดหน้าใหม่ · ระบบต้องเปิดผ่าน <b>https</b> GPS จึงทำงาน (ดู <x-manual.link to="faq" />)</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="leave" title="ยื่นใบลา">
    <x-manual.steps>
        <li>เมนู <span class="ui">ลางาน</span> → <span class="ui">ยื่นใบลา</span></li>
        <li>เลือกประเภท: <b>ลาป่วย · ลากิจส่วนตัว · ลาพักผ่อน · ไปราชการ · ลาคลอดบุตร</b></li>
        <li>วันที่ <b>ตั้งแต่ – ถึง</b> · <b>เหตุผล</b> · ไฟล์แนบ (ใบรับรองแพทย์ หนังสือเชิญประชุม)</li>
        <li>กด <span class="ui">ส่งใบลา</span> สถานะ <b>รออนุมัติ</b> — ผู้ดูแลระบบได้แจ้งเตือนทาง LINE</li>
    </x-manual.steps>
    <x-manual.go route="staff-leaves.index">เปิดหน้าลางาน</x-manual.go>
    <ul>
        <li>การ์ด <span class="ui">วันลาที่ใช้ปีงบนี้</span> สรุปวันลาแต่ละประเภทในปีงบประมาณ (1 ต.ค. – 30 ก.ย.)</li>
        <li>ยกเลิกใบลาได้เองระหว่างที่ยังรออนุมัติ</li>
        <li>ได้แจ้งเตือนทันทีเมื่ออนุมัติ/ไม่อนุมัติ (พร้อมเหตุผล)</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="approve" title="อนุมัติใบลา (ผู้ดูแลระบบ / ผู้บริหาร)">
    <p>หน้าลางาน → ส่วน <span class="ui">รออนุมัติ</span> ดูเหตุผลและไฟล์แนบ กด <span class="ui">อนุมัติ</span> หรือ <span class="ui">ไม่อนุมัติ</span> (ใส่เหตุผลได้)</p>
    <x-manual.callout type="tip">เมื่ออนุมัติ ระบบลงสถานะ <b>ลา</b> / <b>ไปราชการ</b> ในการลงเวลาให้ครูคนนั้นทุกวันทำการในช่วงที่ลาโดยอัตโนมัติ ไม่ต้องให้ครูกดเอง</x-manual.callout>
</x-manual.section>

