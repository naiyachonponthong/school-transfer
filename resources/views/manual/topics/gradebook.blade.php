        <li>เมนู <span class="ui">คะแนน</span> → <span class="ui">เปิดรายวิชา</span></li>
        <li>เลือก <b>รายวิชา</b> (ได้หลายวิชา) × <b>ห้อง</b> (ได้หลายห้อง) และ <b>ครูผู้สอน</b> ระบบสร้างรายวิชาให้ครบทุกคู่ในครั้งเดียว</li>
        <li>เปลี่ยนครูผู้สอนภายหลังได้ที่แถวของรายวิชานั้น</li>
    </x-manual.steps>
