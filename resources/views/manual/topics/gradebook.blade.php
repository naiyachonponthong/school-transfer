</x-manual.section>

<x-manual.section anchor="columns" title="ตั้งช่องคะแนน">
    <x-manual.steps>
        <li>ครูเปิดรายวิชา → <span class="ui">กรอกคะแนน</span> → ปุ่ม <span class="ui">ช่องคะแนน</span></li>
        <li>เพิ่มช่อง เช่น "เก็บ 1" 10 คะแนน · "กลางภาค" 20 · "ปลายภาค" 30 — <b>คะแนนเต็มรวมควรเท่ากับ 100</b> (ระบบเตือนถ้าไม่เท่า)</li>
        <li>ลบช่อง = ลบคะแนนในช่องนั้นทั้งหมด (ถูกบันทึกในประวัติการแก้ไข)</li>
    </x-manual.steps>
</x-manual.section>

<x-manual.section anchor="enter" title="กรอกคะแนน">
    <ul>
        <li>ตารางเหมือน Excel <b>พิมพ์แล้วบันทึกเองอัตโนมัติ</b> ไม่ต้องกดปุ่ม (ดูสถานะมุมบน)</li>
        <li><kbd>Enter</kbd> / <kbd>↓</kbd> ลงคนถัดไป · <kbd>←</kbd> <kbd>→</kbd> เปลี่ยนช่อง</li>
        <li><b>วางทั้งคอลัมน์จาก Excel:</b> คัดลอกคะแนนทั้งคอลัมน์ (เรียงตามเลขที่) แล้ววางที่ช่องของคนแรก</li>
        <li>เกรดคำนวณทันทีตามเกณฑ์: 80–100 = 4 · 75 = 3.5 · 70 = 3 · 65 = 2.5 · 60 = 2 · 55 = 1.5 · 50 = 1 · ต่ำกว่า 50 = 0</li>
        <li>วิชากิจกรรมพัฒนาผู้เรียน ได้ผล <b>ผ</b> (ผ่าน ≥ 50%) / <b>มผ</b> อัตโนมัติ</li>
        <li>ปุ่ม <span class="ui">ส่งออก</span> ได้ไฟล์ Excel · การ์ดด้านล่างแสดงการกระจายเกรดของห้อง</li>
    </ul>
    <x-manual.callout type="tip">คะแนนจาก <x-manual.link to="exams">ตรวจข้อสอบด้วยมือถือ</x-manual.link> และ <x-manual.link to="homework">การบ้าน</x-manual.link> ส่งเข้าช่องคะแนนได้คลิกเดียว ไม่ต้องพิมพ์ซ้ำ</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="special" title="ผลพิเศษ ร / มส / มผ และผลการแก้ตัว">
    <x-manual.steps>
        <li>กดปุ่ม <i class="bi bi-three-dots-vertical"></i> ข้างเกรดของนักเรียน จะมีหน้าต่าง <span class="ui">ผลพิเศษ / แก้ตัว</span></li>
        <li><b>ผลพิเศษ (แทนผลจากคะแนน):</b> <b>ร</b> = รอการตัดสิน/ยังไม่ส่งงาน · <b>มส</b> = ไม่มีสิทธิ์สอบ (เวลาเรียนไม่ถึง 80%) · วิชากิจกรรมใช้ <b>มผ</b></li>
        <li><b>ผลการแก้ตัว</b> + วันที่แก้ตัว + หมายเหตุ: เกรด 0 และ มส แก้ได้สูงสุด <b>1</b> · ร แก้ได้ตามผลจริง · มผ แก้เป็น ผ</li>
        <li>นักเรียนที่เวลาเรียนรายคาบต่ำกว่า 80% — ปุ่ม <span class="ui">ตั้ง มส. ให้ทั้งหมด</span> (วิชากิจกรรม: ตั้ง มผ.) ได้ทีเดียว</li>
    </x-manual.steps>
    <x-manual.callout type="note">ร และ มส นับเป็น 0 ในการคิดผลการเรียนเฉลี่ยจนกว่าจะแก้ตัว · ผลแก้ตัวบันทึกได้แม้รายวิชาล็อกแล้ว และแสดงใน ปพ.1 ปพ.5 ปพ.6</x-manual.callout>
</x-manual.section>

