<x-manual.section anchor="clubs" title="ชุมนุม: ให้นักเรียนเลือกเอง">
    <x-manual.steps>
        <li>เมนู <span class="ui">ชุมนุม</span> → <span class="ui">เพิ่มชุมนุม</span> ใส่ชื่อ ครูที่ปรึกษา จำนวนรับ และระดับชั้นที่รับ</li>
        <li>กำหนด <b>ช่วงที่นักเรียนเลือกชุมนุมเองได้</b> (วันเวลาเปิด-ปิดรับ)</li>
        <li>นักเรียนเข้าเมนู <span class="ui">เลือกชุมนุม</span> เห็นจำนวนที่เหลือ กดเลือกได้คนละ 1 ชุมนุม เปลี่ยนได้จนกว่าจะปิดรับ ชุมนุมที่เต็มแล้วเลือกไม่ได้</li>
        <li>หน้าชุมนุมแสดงรายชื่อนักเรียนที่ยังไม่ได้เลือก ครูที่ปรึกษาเพิ่มหรือนำสมาชิกออกเองได้ตลอด</li>
        <li>เมื่อรายชื่อลงตัว เปิดชุมนุมนั้นแล้วกด <span class="ui">สร้างรายวิชา</span> ครูที่ปรึกษาจะเช็คชื่อรายคาบและประเมินผล ผ/มผ ได้ รายชื่อในรายวิชาตามสมาชิกของชุมนุมอัตโนมัติ</li>
    </x-manual.steps>
