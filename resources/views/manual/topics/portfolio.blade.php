<p>แฟ้มสะสมผลงานดิจิทัลของนักเรียนแต่ละคน เก็บรางวัล ผลงาน กิจกรรม และชั่วโมงจิตอาสาพร้อมรูปถ่าย ใช้ประกอบการสมัครเรียนต่อ/ทุน และพิมพ์เป็นแฟ้มได้</p>

<x-manual.section anchor="open" title="เปิดแฟ้มผลงาน">
    <ul>
        <li><b>ครู:</b> หน้าข้อมูลนักเรียน → <span class="ui">แฟ้มผลงาน</span></li>
        <li><b>ผู้ปกครอง:</b> เมนู <span class="ui">แฟ้มผลงาน</span> หรือหน้าบุตรหลาน → ชิป <span class="ui">แฟ้มผลงาน</span></li>
        <li><b>นักเรียน:</b> เมนู <span class="ui">แฟ้มผลงาน</span></li>
    </ul>
</x-manual.section>

<x-manual.section anchor="add" title="เพิ่มผลงาน">
    <x-manual.steps>
        <li>กด <span class="ui">เพิ่มผลงาน</span> เลือกประเภท: <b>รางวัล/เกียรติบัตร · ผลงาน/ชิ้นงาน · กิจกรรม · จิตอาสา</b></li>
        <li>ใส่ <b>ชื่อผลงาน / รางวัล</b> รายละเอียด <b>ระดับ</b> (โรงเรียน เขตพื้นที่ จังหวัด ภาค ประเทศ นานาชาติ) วันที่</li>
        <li>กิจกรรม/จิตอาสาใส่ <b>ชั่วโมง</b> ได้ (ละเอียดครึ่งชั่วโมง) · แนบ<b>รูป</b>เกียรติบัตรหรือภาพกิจกรรม (ไม่เกิน 6 MB)</li>
        <li>กด <span class="ui">บันทึก</span></li>
    </x-manual.steps>
    <x-manual.callout type="tip">ครูบันทึกรางวัลแล้วติ๊ก <span class="ui">แชร์รางวัลลงฟีดข่าวโรงเรียน</span> ระบบโพสต์ประกาศเกียรติคุณให้ทันที — ดู <x-manual.link to="communication" /></x-manual.callout>
</x-manual.section>

<x-manual.section anchor="verify" title="การรับรองผลงาน">
    <ul>
        <li>ผลงานที่<b>ครู</b>บันทึก = รับรองแล้วทันที</li>
        <li>ผลงานที่<b>นักเรียน/ผู้ปกครอง</b>เพิ่ม จะมีป้าย <span class="badge bg-warning text-dark">รอรับรอง</span> ครูเปิดแฟ้มแล้วกด <span class="ui">รับรอง</span> หลังตรวจหลักฐาน</li>
        <li><b>ชั่วโมงกิจกรรม/จิตอาสา</b>ที่ด้านบนแฟ้มนับเฉพาะรายการที่รับรองแล้ว</li>
        <li>ลบได้เฉพาะคนที่บันทึกรายการนั้น และผู้ดูแลระบบ</li>
    </ul>
</x-manual.section>

<x-manual.section anchor="print" title="พิมพ์แฟ้มผลงาน">
    <p>กด <span class="ui">พิมพ์</span> มุมขวาบน ได้เอกสารรวมผลงานทุกรายการพร้อมรูป ชื่อนักเรียน ห้อง และสรุปชั่วโมง เลือก "บันทึกเป็น PDF" ในหน้าพิมพ์เพื่อเก็บเป็นไฟล์</p>
</x-manual.section>
