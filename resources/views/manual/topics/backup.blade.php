<x-manual.section anchor="delete" title="ทำไมลบบางอย่างไม่ได้">
    <p>เพื่อกันข้อมูลหาย ระบบยอมให้ลบเฉพาะสิ่งที่บันทึกผิดและยังไม่มีประวัติ เช่น</p>
    <ul>
        <li><b>นักเรียน</b> ที่มีคะแนน การมาเรียน ใบแจ้งหนี้ หรือเอกสาร ปพ. แล้ว → เปลี่ยนสถานะเป็นย้าย/ลาออก/จบแทน</li>
        <li><b>รายวิชา</b> ที่มีคะแนน ผลการเรียน หรือเช็คชื่อรายคาบแล้ว</li>
        <li><b>ครุภัณฑ์ / ตัวเล่มหนังสือ</b> ที่มีประวัติซ่อม/ตรวจนับ/ยืมแล้ว → เปลี่ยนสถานะเป็นจำหน่ายแทน</li>
    </ul>
