<x-manual.section anchor="receipt" title="ใบเสร็จ">
    <p>หลังตัดเงิน กด <span class="ui">พิมพ์ใบเสร็จล่าสุด</span> หรือรูปเครื่องพิมพ์ที่รายการในตาราง ใบเสร็จออกแบบสำหรับกระดาษความร้อน 58 มม. ติ๊ก <span class="ui">พิมพ์ใบเสร็จทุกครั้ง</span> เพื่อให้เปิดหน้าพิมพ์เองหลังขายทุกรายการ (เครื่องจะจำค่านี้ไว้)</p>
    <x-manual.callout type="note">การพิมพ์ใช้ระบบพิมพ์ของเบราว์เซอร์ จึงใช้ได้กับเครื่องพิมพ์ใบเสร็จที่ติดตั้งในคอมพิวเตอร์หรือแท็บเล็ตแล้ว เครื่องพิมพ์ในตัวของเครื่อง POS บางรุ่นต้องตั้งเป็นเครื่องพิมพ์ของระบบก่อน</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="auto" title="เติมเงินอัตโนมัติผ่านธนาคาร">
    <p>เมื่อโรงเรียนสมัครบริการรับชำระบิล (Bill Payment) กับธนาคารแล้ว ผู้ปกครองจะได้ QR ที่มีเลขอ้างอิงของรายการ จ่ายแล้วเงินเข้ากระเป๋าเองโดยไม่ต้องแนบสลิปและไม่ต้องรอตรวจ</p>
    <x-manual.steps>
        <li>เมนู <span class="ui">กระเป๋าเงิน</span> → การ์ด <span class="ui">เติมเงินอัตโนมัติผ่านธนาคาร</span> ใส่ <b>Biller ID</b> 15 หลักที่ธนาคารออกให้ แล้วบันทึก</li>
        <li>ระบบออก<b>รหัสลับ</b>ให้และแสดงครั้งเดียว คัดลอกไปให้ผู้เชื่อมระบบกับธนาคาร พร้อม<b>ที่อยู่รับแจ้งผลการชำระ</b></li>
        <li>ธนาคารหรือตัวกลางส่งผลการชำระมาที่ที่อยู่นั้น ระบบตรวจลายเซ็น เลขอ้างอิง และยอดเงิน แล้วเติมเงินให้ รายการเดิมส่งซ้ำไม่ทำให้เงินเข้าซ้ำ</li>
    </x-manual.steps>
    <p>ข้อความที่ระบบรับ เป็น <code>POST</code> แบบ JSON พร้อม header <code>X-Signature</code> = HMAC-SHA256 ของเนื้อความด้วยรหัสลับ:</p>
<pre class="small bg-light border rounded p-2">{"reference": "WABC123XYZ45", "amount": 150.00, "transaction_id": "เลขรายการของธนาคาร"}</pre>
    <x-manual.callout type="warn">ธนาคารแต่ละแห่งส่งข้อมูลในรูปแบบของตัวเอง ตอนเชื่อมจริงต้องมีการแปลงให้เป็นรูปแบบข้างต้น และต้องทดสอบกับธนาคารก่อนเปิดใช้ ระหว่างที่ยังไม่ได้ตั้งค่า ผู้ปกครองเติมเงินด้วยการแนบสลิปหรือเงินสดได้ตามเดิม</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="staff" title="กระเป๋าเงินของครูและบุคลากร">
    <p>ครูและบุคลากรมีกระเป๋าเงินของตัวเอง ใช้ซื้อของที่ร้านในโรงเรียนได้เหมือนนักเรียน</p>
    <ul>
        <li>เปิดเมนู <span class="ui">กระเป๋าเงินของฉัน</span> ดูยอดและรายการ เติมเงินด้วยการโอนแล้วแนบสลิป (หรือสแกนจ่ายอัตโนมัติถ้าโรงเรียนเปิดใช้) ตั้งวงเงินต่อวัน และระงับการใช้จ่ายได้เอง</li>
        <li>เติมเงินสดที่ห้องการเงิน: ฝ่ายการเงินเลือกชื่อในกลุ่ม "ครูและบุคลากร" หรือพิมพ์รหัสบุคลากรที่ช่องสแกน</li>
        <li>ตอนซื้อของ บอก<b>รหัสบุคลากร</b>ให้คนขายพิมพ์ที่ช่องสแกน (คนที่ยังไม่มีรหัสใช้ชื่อผู้ใช้แทนได้) จอจะขึ้นรูปและชื่อให้คนขายตรวจก่อนตัดเงิน</li>
    </ul>
