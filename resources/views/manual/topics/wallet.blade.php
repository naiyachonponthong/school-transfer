<x-manual.section anchor="qrpay" title="ให้ลูกค้าสแกน QR จ่ายเอง">
    <p>ลูกค้าที่ไม่มีเงินในกระเป๋า หรือผู้ปกครองและบุคคลภายนอก จ่ายด้วยแอปธนาคารได้: ที่หน้าจอขาย ใส่รายการแล้วกด <span class="ui">ให้ลูกค้าสแกนจ่าย (QR พร้อมเพย์)</span> ระบบสร้าง QR ที่ใส่ยอดให้แล้ว เมื่อเห็นเงินเข้าจึงกด <span class="ui">ได้รับเงินแล้ว</span></p>
    <ul>
        <li>เงินเข้าพร้อมเพย์ของร้านถ้าตั้งไว้ในหน้าร้าน ถ้าไม่ได้ตั้งจะเข้าพร้อมเพย์ของโรงเรียน ปุ่มนี้ไม่ขึ้นถ้ายังไม่ได้ตั้งพร้อมเพย์ทั้งสองที่</li>
        <li>รายการแบบนี้ไม่เกี่ยวกับกระเป๋าเงินของใคร รายงานแยกยอด "จากกระเป๋า" กับ "QR" ให้ และใบเสร็จระบุว่าชำระด้วย QR</li>
        <li>ยกเลิกรายการที่จ่ายด้วย QR ระบบคืนสต็อกให้ แต่<b>ต้องคืนเงินให้ลูกค้าเอง</b></li>
    </ul>
    <x-manual.callout type="warn">ระบบไม่รู้เองว่าเงินเข้าบัญชีแล้วหรือยัง คนขายต้อง<b>ตรวจยอดเงินเข้าในแอปธนาคารของร้าน</b>ก่อนกดยืนยัน อย่าดูจากสลิปบนมือถือลูกค้าอย่างเดียว เพราะสลิปปลอมทำได้ง่าย</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="display" title="หน้าจอลูกค้า">
    <p>จอที่หันหาลูกค้า แสดงรายการ ยอดรวม ชื่อและยอดคงเหลือหลังแตะบัตร QR สำหรับสแกนจ่าย และผลการชำระ ตามที่คนขายกดที่หน้าจอขาย (ช้ากว่าราวหนึ่งวินาที)</p>
