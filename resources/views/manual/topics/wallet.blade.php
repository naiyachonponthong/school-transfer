<p>นักเรียนแต่ละคนมีกระเป๋าเงินในระบบ ผู้ปกครองเติมเงิน นักเรียนใช้บัตรนักเรียนจ่ายที่ร้านในโรงเรียนแทนเงินสด ผู้ปกครองเห็นทุกรายการที่ลูกซื้อ</p>

<x-manual.section anchor="parent" title="ผู้ปกครอง: ดูยอด เติมเงิน และควบคุมการใช้จ่าย">
    <x-manual.steps>
        <li>เปิดเมนู <span class="ui">กระเป๋าเงิน</span> เห็นยอดคงเหลือและรายการซื้อของลูก (ซื้ออะไร ร้านไหน กี่โมง)</li>
        <li><b>เติมเงินด้วยการโอน</b>: เลือกจำนวนเงิน สแกน QR พร้อมเพย์ด้วยแอปธนาคาร แล้วแนบสลิป เงินเข้ากระเป๋าเมื่อฝ่ายการเงินตรวจสลิปแล้ว</li>
        <li><b>เติมเงินสด</b>: นำเงินไปที่ห้องการเงิน เงินเข้ากระเป๋าทันที</li>
        <li>ตั้ง <span class="ui">วงเงินใช้จ่ายต่อวัน</span> ได้ และเปิด <span class="ui">ระงับการใช้จ่าย</span> ทันทีเมื่อบัตรหาย</li>
    </x-manual.steps>
    <x-manual.go route="parent.wallet">เปิดกระเป๋าเงิน</x-manual.go>
    <x-manual.callout type="note">ระบบแจ้งเตือนทาง LINE/แจ้งเตือนในเครื่องทุกครั้งที่ลูกซื้อของ และเมื่อยอดเหลือน้อยกว่า 20 บาท นักเรียนดูยอดและรายการของตัวเองได้ แต่เติมเงินหรือแก้การตั้งค่าไม่ได้</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="pos" title="ร้านค้า: หน้าจอขาย">
    <x-manual.steps>
        <li>เปิดเมนู <span class="ui">หน้าจอขาย</span> (ถ้าขายได้หลายร้านให้เลือกร้าน)</li>
        <li>กดสินค้าที่ขาย หรือใส่ <span class="ui">จำนวนเงินอื่น</span> แล้วกดเพิ่ม</li>
        <li>สแกนบัตรนักเรียนด้วยเครื่องอ่านบาร์โค้ด หรือกด <span class="ui">สแกนด้วยกล้อง</span> หรือพิมพ์รหัสนักเรียนแล้วกด Enter</li>
        <li>จอขึ้นรูป ชื่อ ห้อง และยอดคงเหลือ <b>เทียบหน้านักเรียนกับรูป</b> แล้วกด <span class="ui">ตัดเงิน</span></li>
    </x-manual.steps>
    <x-manual.go route="pos.index">เปิดหน้าจอขาย</x-manual.go>
    <ul>
        <li>ถ้ายอดไม่พอ เกินวงเงินต่อวัน หรือกระเป๋าถูกระงับ ปุ่มตัดเงินจะกดไม่ได้และบอกสาเหตุ</li>
        <li>กดผิด: กด <span class="ui">ยกเลิก</span> ที่รายการในตาราง "ขายล่าสุดวันนี้" ใส่เหตุผล เงินคืนเข้ากระเป๋านักเรียนทันที (ผู้ขายยกเลิกได้เฉพาะรายการของวันนี้)</li>
        <li>เน็ตสะดุดตอนกดตัดเงิน กดซ้ำได้ ระบบไม่ตัดเงินสองครั้ง</li>
    </ul>
    <x-manual.callout type="tip">หน้าจอขายใช้ได้บนแท็บเล็ต คอมพิวเตอร์ และเครื่อง POS แบบ Android ที่เปิดเบราว์เซอร์ได้ เครื่องอ่านบาร์โค้ดหรือเครื่องอ่านบัตรแบบ USB ที่ส่งรหัสเหมือนพิมพ์คีย์บอร์ดใช้ได้เลย ต้องมีอินเทอร์เน็ตตลอดเวลาที่ขาย</x-manual.callout>
</x-manual.section>

<x-manual.section anchor="admin" title="ฝ่ายการเงิน: เติมเงิน ตรวจสลิป ร้านค้า รายงาน">
    <x-manual.steps>
        <li>เมนู <span class="ui">กระเป๋าเงิน</span> → <span class="ui">เติมเงินสด</span>: เลือกนักเรียน ใส่จำนวนเงิน เงินเข้าทันที</li>
        <li><span class="ui">สลิปเติมเงินรอตรวจ</span>: เปิดดูสลิป เทียบยอดกับบัญชีโรงเรียน แล้วกด <span class="ui">อนุมัติ</span> หรือ <span class="ui">ไม่อนุมัติ</span> พร้อมเหตุผล</li>
        <li><span class="ui">เพิ่มร้านค้า</span> แล้วกด <span class="ui">จัดการ</span> เพื่อเพิ่มสินค้า ราคา และกำหนดผู้ขายของร้าน</li>
        <li><span class="ui">รายงาน</span>: ยอดขายแยกร้านและสินค้า (ใช้เป็นยอดจ่ายให้ร้าน) ยอดเติมแยกช่องทาง และเงินคงค้างในกระเป๋าทั้งหมด เลือกช่วงวันที่และพิมพ์ได้</li>
    </x-manual.steps>
    <x-manual.go route="wallets.index" admin>เปิดหน้ากระเป๋าเงิน</x-manual.go>
    <ul>
        <li><b>บัญชีของคนขาย</b>: สร้างบัญชีที่เมนูผู้ใช้งาน กำหนดตำแหน่ง <b>ผู้ขาย/ร้านค้า</b> แล้วติ๊กชื่อในหน้าร้าน คนขายเห็นเฉพาะร้านของตัวเอง</li>
        <li><b>นักเรียนจบหรือย้ายออก</b>: เปิดกระเป๋าของนักเรียน (กดชื่อในรายการ) → <span class="ui">ปรับยอด / ถอนคืน</span> → ถอนเงินคืนผู้ปกครอง</li>
        <li>สมุดรายการของกระเป๋าแก้หรือลบย้อนหลังไม่ได้ ถ้าผิดให้ยกเลิกรายการขายหรือปรับยอดพร้อมเหตุผล ทุกครั้งถูกบันทึกในประวัติการแก้ไข</li>
    </ul>
    <x-manual.callout type="warn">เงินในกระเป๋าเป็นเงินของผู้ปกครองที่โรงเรียนถือไว้ ควรเก็บแยกจากรายรับของโรงเรียน และตรวจยอด "เงินคงค้างในกระเป๋า" กับเงินที่ถือจริงเป็นประจำ การเปิดให้ร้านค้าภายนอกรับชำระด้วยมูลค่าเงินที่เติมไว้ล่วงหน้าอาจเกี่ยวข้องกับกฎเกณฑ์เงินอิเล็กทรอนิกส์ ควรปรึกษาผู้รู้กฎหมายก่อนเปิดใช้จริง</x-manual.callout>
</x-manual.section>
