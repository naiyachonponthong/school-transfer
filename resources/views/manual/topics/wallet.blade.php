        <li><span class="ui">เพิ่มร้านค้า</span> แล้วกด <span class="ui">จัดการ</span> เพื่อเพิ่มสินค้า ราคา และกำหนดผู้ขายของร้าน</li>
        <li><span class="ui">รายงาน</span>: ยอดขายแยกร้านและสินค้า (ใช้เป็นยอดจ่ายให้ร้าน) ยอดเติมแยกช่องทาง และเงินคงค้างในกระเป๋าทั้งหมด เลือกช่วงวันที่และพิมพ์ได้</li>
