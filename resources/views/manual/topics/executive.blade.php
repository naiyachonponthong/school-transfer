<x-manual.section anchor="export" title="ส่งออกและลบข้อมูล">
    <ul>
        <li><b>ส่งออกข้อมูลนักเรียนรายคน</b> เมื่อเจ้าของข้อมูลหรือผู้ปกครองขอสำเนา ผู้มีสิทธิ์จัดการผู้ใช้กดได้ที่ท้ายหน้าข้อมูลนักเรียน</li>
        <li><b>ไฟล์ส่วนตัว</b> เช่น สลิป ใบรับรองแพทย์ รูปเยี่ยมบ้าน ลายเซ็น เก็บนอกโฟลเดอร์สาธารณะ เปิดได้เฉพาะผู้เกี่ยวข้อง</li>
        <li>ผู้ดูแลเครื่องเซิร์ฟเวอร์ลบข้อมูลของนักเรียนที่พ้นระยะเก็บรักษาได้ด้วยคำสั่ง <code>php artisan privacy:purge</code></li>
    </ul>
</x-manual.section>

<x-manual.section anchor="demo" title="โหมดทดลองใช้ (สำหรับระบบสาธิต)">
    <p>เปิดให้คนภายนอกกดเข้าดูระบบจากหน้าเข้าสู่ระบบได้โดยไม่ต้องมีรหัสผ่าน เหมาะกับเว็บสาธิตที่ใช้แนะนำระบบ <b>อย่าเปิดบนระบบที่มีข้อมูลจริง</b></p>
    <x-manual.steps>
        <li>หน้าตั้งค่า → การ์ด <b>โหมดทดลองใช้</b> เลือกผู้ใช้ที่จะเป็นบัญชีทดลองของแต่ละบทบาท (ผู้บริหาร ครู ผู้ปกครอง นักเรียน) เลือกผู้ดูแลระบบไม่ได้</li>
        <li>เตรียมข้อมูลตัวอย่างให้เรียบร้อย แล้วกด <span class="ui">บันทึกต้นแบบ</span></li>
        <li>เปิดสวิตช์ <b>เปิดโหมดทดลองใช้</b> และ <b>คืนข้อมูลเป็นต้นแบบทุกคืน</b> → <span class="ui">บันทึกโหมดทดลองใช้</span></li>
    </x-manual.steps>
    <x-manual.go route="settings">เปิดหน้าตั้งค่า</x-manual.go>
    <ul>
        <li>ผู้ทดลองเปลี่ยนรหัสผ่าน แก้ข้อมูลบัญชี ตั้งค่า จัดการผู้ใช้ สำรอง/ส่งออกข้อมูล และลบข้อมูลไม่ได้ · บทบาทผู้บริหารดูได้อย่างเดียว</li>
        <li>การคืนค่าทุกคืน (03:30) ต้องตั้งเวลารันคำสั่งประจำของระบบไว้ และ<b>หลังอัปเดตเวอร์ชันต้องบันทึกต้นแบบใหม่</b></li>
        <li>การคืนค่าจะย้อนข้อมูลทั้งฐานข้อมูลกลับไปเป็นต้นแบบ รวมการตั้งค่าที่แก้หลังบันทึกต้นแบบ · ไฟล์ที่อัปโหลดระหว่างวันไม่ถูกลบ</li>
    </ul>
</x-manual.section>
