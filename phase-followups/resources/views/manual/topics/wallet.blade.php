        <li>รายการขายที่จ่ายเงินให้ร้านแล้ว<b>ยกเลิกไม่ได้</b> (ไม่อย่างนั้นเงินจะออกสองทาง: คืนเข้ากระเป๋าและจ่ายให้ร้าน) ถ้าจำเป็นให้ยกเลิกใบจ่ายเงินก่อน</li>
        <li><b>จ่ายผิด</b>: เปิดใบจ่ายเงิน → <span class="ui">ยกเลิกใบนี้</span> ใส่เหตุผล ยอดขายในใบกลับไปเป็นยอดค้างจ่าย แล้วออกใบใหม่ เลขที่ใบเดิมเก็บไว้ ไม่ถูกใช้ซ้ำ</li>
        <li>เปลี่ยนอัตราส่วนแบ่งมีผลกับใบถัดไป ใบที่ออกแล้วใช้อัตรา ณ วันที่จ่าย และการเปลี่ยนอัตราถูกบันทึกในประวัติการแก้ไข</li>
    </ul>
