<x-manual.section anchor="settlement" title="จ่ายเงินยอดขายให้ร้านค้า">
    <p>ค่าสินค้าถูกตัดจากกระเป๋าเงินมาอยู่ที่โรงเรียน โรงเรียนจึงต้องจ่ายยอดขายคืนให้ร้านเป็นงวด (เช่น ทุกวันหรือทุกสัปดาห์) ระบบจำว่ารายการขายใดจ่ายให้ร้านไปแล้ว จึงไม่จ่ายซ้ำและไม่ตกหล่น</p>
    <x-manual.steps>
        <li>ครั้งแรก: เปิดหน้าร้าน (เมนู <span class="ui">กระเป๋าเงิน</span> → <span class="ui">จัดการ</span>) ใส่ <span class="ui">ส่วนแบ่งของโรงเรียน (%)</span> ถ้ามี และ <span class="ui">ช่องทางรับเงินของร้าน</span></li>
        <li>เมนู <span class="ui">กระเป๋าเงิน</span> → <span class="ui">จ่ายเงินร้านค้า</span> เห็นยอดขายค้างจ่ายของแต่ละร้าน ส่วนแบ่ง และยอดที่ต้องจ่าย เลือกได้ว่านับยอดขายถึงวันไหน</li>
        <li>กด <span class="ui">จ่ายเงิน</span> ที่ร้าน เลือกวิธีจ่าย (เงินสด/โอน) แล้วบันทึก ระบบออก <b>ใบจ่ายเงิน</b> มีเลขที่ สรุปยอดขายรายวัน และช่องให้ร้านลงชื่อรับเงิน</li>
        <li>พิมพ์ใบจ่ายเงินให้ร้านเซ็นรับ เก็บไว้เป็นหลักฐาน</li>
    </x-manual.steps>
